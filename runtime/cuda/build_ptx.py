"""Compile runtime/cuda/*.cu to PTX with NVRTC and write runtime/vira_cuda_<name>_ptx.h.

    pip install nvidia-cuda-nvrtc-cu11==11.8.89     # NVRTC 11.8: PTX ISA 7.8
    python3 runtime/cuda/build_ptx.py [--check]

NVRTC 11.8 on purpose: drivers refuse PTX newer than they know (CUDA error 222), and
11.8 PTX loads on every driver from 520 on. Target compute_61 (dp4a); the driver
compiles the PTX for the GPU it runs on. With --check, ptxas (pip
nvidia-cuda-nvcc-cu12) also assembles the PTX for sm_61, sm_75 and sm_86.
"""
import ctypes, glob, os, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
RUNTIME = os.path.dirname(HERE)
ARCH = 'compute_61'


def find_nvrtc():
    import site
    for base in site.getsitepackages() + [site.getusersitepackages()]:
        for p in sorted(glob.glob(os.path.join(base, 'nvidia', 'cuda_nvrtc', 'lib', 'libnvrtc.so.11*'))):
            return p
    sys.exit('libnvrtc.so.11 not found: pip install nvidia-cuda-nvrtc-cu11==11.8.89')


def compile_ptx(lib, path):
    src = open(path, 'rb').read()
    prog = ctypes.c_void_p()
    name = os.path.basename(path).encode()
    rc = lib.nvrtcCreateProgram(ctypes.byref(prog), src, name, 0, None, None)
    assert rc == 0, 'nvrtcCreateProgram %d' % rc
    # No --use_fast_math: it flushes denormals (.ftz), and the fused kernels must repeat
    # the arithmetic of the separate kernels exactly.
    opts = [('--gpu-architecture=%s' % ARCH).encode(), b'--std=c++14', b'-default-device']
    arr = (ctypes.c_char_p * len(opts))(*opts)
    rc = lib.nvrtcCompileProgram(prog, len(opts), arr)
    log_size = ctypes.c_size_t()
    lib.nvrtcGetProgramLogSize(prog, ctypes.byref(log_size))
    log = ctypes.create_string_buffer(log_size.value)
    lib.nvrtcGetProgramLog(prog, log)
    if rc != 0:
        sys.exit('%s:\n%s' % (path, log.value.decode()))
    size = ctypes.c_size_t()
    lib.nvrtcGetPTXSize(prog, ctypes.byref(size))
    ptx = ctypes.create_string_buffer(size.value)
    lib.nvrtcGetPTX(prog, ptx)
    lib.nvrtcDestroyProgram(ctypes.byref(prog))
    return ptx.value.decode()


def c_string(ptx):
    lines = []
    for line in ptx.splitlines():
        esc = line.replace('\\', '\\\\').replace('"', '\\"')
        lines.append('    "%s\\n"' % esc)
    return '\n'.join(lines)


def ptxas_check(ptx, stem):
    import site
    ptxas = None
    for base in site.getsitepackages():
        p = os.path.join(base, 'nvidia', 'cuda_nvcc', 'bin', 'ptxas')
        if os.path.exists(p):
            ptxas = p
    if ptxas is None:
        print('  ptxas not found (pip install nvidia-cuda-nvcc-cu12): not checked')
        return
    tmp = '/tmp/%s.ptx' % stem
    open(tmp, 'w').write(ptx)
    for sm in ('sm_61', 'sm_75', 'sm_86'):
        r = subprocess.run([ptxas, '-arch=' + sm, '-v', tmp, '-o', '/dev/null'],
                           capture_output=True, text=True)
        regs = [l.strip() for l in r.stderr.splitlines() if 'registers' in l]
        print('  ptxas %s: %s %s' % (sm, 'ok' if r.returncode == 0 else 'FAILED', '; '.join(regs)))
        if r.returncode != 0:
            sys.exit(r.stderr)


def main():
    lib = ctypes.CDLL(find_nvrtc())
    for path in sorted(glob.glob(os.path.join(HERE, '*.cu'))):
        stem = os.path.splitext(os.path.basename(path))[0]
        ptx = compile_ptx(lib, path)
        out = os.path.join(RUNTIME, 'vira_cuda_%s_ptx.h' % stem)
        guard = 'VIRA_CUDA_%s_PTX_H' % stem.upper()
        with open(out, 'w') as f:
            f.write('// Generated by runtime/cuda/build_ptx.py from runtime/cuda/%s.cu. Do not edit.\n' % os.path.basename(path))
            f.write('#ifndef %s\n#define %s\n\n' % (guard, guard))
            f.write('static const char *_vira_cuda_%s_ptx =\n%s;\n\n#endif\n' % (stem, c_string(ptx)))
        print('%s -> %s (%d bytes of PTX)' % (os.path.relpath(path, RUNTIME), os.path.relpath(out, RUNTIME), len(ptx)))
        if '--check' in sys.argv:
            ptxas_check(ptx, stem)


if __name__ == '__main__':
    main()
