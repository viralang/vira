			if st, isSt := g.chk.Structs()[identLeft.Ident.Name]; isSt {
				return fmt.Sprintf("%s_%s(%s)",
					g.cStructName(st.Name), callee.Field.Name, strings.Join(argStrs, ", "))
			}
