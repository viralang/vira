func (g *Generator) fnSignature(fn *ast.FnDecl) string {
	prevMod := g.currentMod
	if fn.Module != "" {
		g.currentMod = fn.Module
	}
	defer func() { g.currentMod = prevMod }()

	retType := g.resolveCheckType(fn)
	cRet := g.cType(retType)

	var cName string
	var params []string

	if fn.Receiver != nil {
		var stName string
		if it, ok := fn.Receiver.Type.(*ast.IdentType); ok {
			stName = it.Name.Name
		} else if st, ok := fn.Receiver.Type.(*ast.SelectorType); ok {
			stName = st.Name.Name
		}
		cSt := fmt.Sprintf("%s__%s", fn.Module, stName)
		if fn.Module == "" {
			cSt = g.cStructName(stName)
		}
		cName = fmt.Sprintf("%s_%s", cSt, fn.Name.Name)
		qual := fmt.Sprintf("const %s*", cSt)
		if fn.Receiver.IsMut {
			qual = fmt.Sprintf("%s*", cSt)
		}
		params = append(params, fmt.Sprintf("%s %s", qual, fn.Receiver.Name.Name))
	} else if fn.StaticType != nil {
		cSt := fmt.Sprintf("%s__%s", fn.Module, fn.StaticType.Name)
		if fn.Module == "" {
			cSt = g.cStructName(fn.StaticType.Name)
		}
		cName = fmt.Sprintf("%s_%s", cSt, fn.Name.Name)
	} else if fn.Name.Name == "main" {
		cName = "main"
	} else {
		fnMod := fn.Module
		if fnMod == "" {
			fnMod = g.currentModule()
		}
		cName = fmt.Sprintf("%s__%s", fnMod, fn.Name.Name)
	}

	for _, p := range fn.Params {
		pType := g.resolveParamType(fn, p.Name.Name)
		if p.IsMut {
			params = append(params, fmt.Sprintf("%s* %s", g.cType(pType), p.Name.Name))
		} else {
			params = append(params, fmt.Sprintf("%s %s", g.cType(pType), p.Name.Name))
		}
	}

	if len(params) == 0 {
		params = append(params, "void")
	}
	return fmt.Sprintf("%s %s(%s)", cRet, cName, strings.Join(params, ", "))
}

func collectFnDeferVarNames(b *ast.BlockStmt, out map[string]bool) {
	if b == nil {
		return
	}
	for _, stmt := range b.Stmts {
		switch s := stmt.(type) {
		case *ast.DeferFreeStmt:
			out[s.VarName] = true
		case *ast.VarDeclStmt:
			if call, ok := s.Value.(*ast.CallExpr); ok && call.OrBlock != nil {
				out["__or_err__"] = true
				collectFnDeferVarNames(call.OrBlock, out)
			}
		case *ast.AssignStmt:
			if call, ok := s.Value.(*ast.CallExpr); ok && call.OrBlock != nil {
				out["__or_err__"] = true
				collectFnDeferVarNames(call.OrBlock, out)
			}
		case *ast.ExprStmt:
			if call, ok := s.Expr.(*ast.CallExpr); ok && call.OrBlock != nil {
				out["__or_err__"] = true
				collectFnDeferVarNames(call.OrBlock, out)
			}
		case *ast.IfStmt:
			collectFnDeferVarNames(s.Then, out)
			collectFnDeferVarNames(s.Else, out)
		case *ast.SwitchStmt:
			for _, cs := range s.Cases {
				collectFnDeferVarNames(&ast.BlockStmt{Stmts: cs.Body}, out)
			}
		case *ast.ForStmt:
			collectFnDeferVarNames(s.Body, out)
		case *ast.ForInStmt:
			collectFnDeferVarNames(s.Body, out)
		case *ast.ArenaStmt:
			collectFnDeferVarNames(s.Body, out)
		}
	}
}

func (g *Generator) emitFnDecl(out *strings.Builder, fn *ast.FnDecl) {
	if fn.Intrinsic != "" && fn.Body == nil {
		return
	}
	prevMod := g.currentMod
	if fn.Module != "" {
		g.currentMod = fn.Module
	}
	defer func() { g.currentMod = prevMod }()

	prevDeferVars := g.fnDeferVarNames
	prevHasDeferBase := g.hasFnDeferBase
	prevLoopDepth := g.loopDepth
	prevActiveErrs := g.activeErrVars
	g.fnDeferVarNames = make(map[string]bool)
	g.hasFnDeferBase = false
	g.loopDepth = 0
	g.activeErrVars = nil
	collectFnDeferVarNames(fn.Body, g.fnDeferVarNames)
	defer func() {
		g.fnDeferVarNames = prevDeferVars
		g.hasFnDeferBase = prevHasDeferBase
		g.loopDepth = prevLoopDepth
		g.activeErrVars = prevActiveErrs
	}()

	if fn.Name.Name == "main" {
		g.inMainFn = true
		out.WriteString("int main(void) {\n")
		g.emitBlockStmts(out, fn.Body, "    ", nil)
		out.WriteString("    vira_report_mem_stats();\n")
		out.WriteString("    return 0;\n")
		out.WriteString("}\n\n")
		g.inMainFn = false
		return
	}

	prevReceiver := g.curReceiver
	if fn.Receiver != nil {
		g.curReceiver = fn.Receiver.Name.Name
	} else {
		g.curReceiver = ""
	}

	prevPtrParams := g.curPtrParams
	g.curPtrParams = make(map[string]bool)
	for _, p := range fn.Params {
		if p.IsMut {
			g.curPtrParams[p.Name.Name] = true
		}
	}

	// If this is a method on an Actor, bind its isolated scratch arena automatically
	prevArena := g.activeArena
	if fn.Receiver != nil {
		stName := fn.Receiver.Type.(*ast.IdentType).Name.Name
		if st := g.chk.LookupStruct(stName); st != nil && st.IsActor && fn.Receiver.IsMut {
			g.activeArena = fmt.Sprintf("(&%s->_ctx.isolated_heap)", fn.Receiver.Name.Name)
		}
	}

	retType := g.resolveCheckType(fn)
	out.WriteString(g.fnSignature(fn) + " {\n")
	if len(g.fnDeferVarNames) > 0 {
		g.hasFnDeferBase = true
		out.WriteString("    int32_t _vira_defer_base = _vira_actor_defer_mark();\n")
		out.WriteString("    (void)_vira_defer_base;\n")
	}
	g.emitBlockStmts(out, fn.Body, "    ", retType)
	if g.hasFnDeferBase {
		endsWithRet := false
		if fn.Body != nil && len(fn.Body.Stmts) > 0 {
			if _, ok := fn.Body.Stmts[len(fn.Body.Stmts)-1].(*ast.ReturnStmt); ok {
				endsWithRet = true
			}
		}
		if !endsWithRet {
			out.WriteString("    _vira_actor_defer_restore(_vira_defer_base);\n")
		}
	}
	out.WriteString("}\n\n")

	g.activeArena = prevArena
	g.curReceiver = prevReceiver
	g.curPtrParams = prevPtrParams
}

func (g *Generator) emitBlockStmts(out *strings.Builder, b *ast.BlockStmt, indent string, fnRet checker.Type) {
	if b == nil {
		return
	}
	for _, stmt := range b.Stmts {
		g.emitStmt(out, stmt, indent, fnRet)
	}
}

func (g *Generator) tryEmitDetachedActorSend(expr ast.Expr) (string, bool) {
	call, ok := expr.(*ast.CallExpr)
	if !ok || call.OrBlock != nil || call.Propagate {
		return "", false
	}
	callee, isSel := call.Callee.(*ast.SelectorExpr)
	if !isSel || !callee.IsActorSend {
		return "", false
	}
	leftType := g.chk.ExprTypes[callee.Left]
	st, isStruct := leftType.(*checker.StructType)
	if !isStruct || !st.IsActor {
		return "", false
	}

	recvExpr := g.emitLValue(callee.Left)
	isPtr := false
	if ident, ok := callee.Left.(*ast.IdentExpr); ok && g.isPointerReceiverVar(ident.Ident.Name) {
		isPtr = true
	}

	targetStruct := st.Name
	if hops, hasHops := g.chk.SelectorPaths[callee]; hasHops && len(hops) > 0 {
		sep := "."
		if isPtr {
			sep = "->"
		}
		recvExpr = fmt.Sprintf("&%s%s%s", recvExpr, sep, strings.Join(hops, "."))
		targetStruct = hops[len(hops)-1]
	} else if !isPtr {
		recvExpr = "&" + recvExpr
	}

	var argStrs []string
	for _, arg := range call.Args {
		argStrs = append(argStrs, g.emitExpr(arg.Expr))
	}
	allArgs := append([]string{recvExpr}, argStrs...)

	return fmt.Sprintf("%s_send_detached_%s(%s)",
		g.cStructName(targetStruct), callee.Field.Name, strings.Join(allArgs, ", ")), true
}

func isFreshOwningRValue(expr ast.Expr) bool {
	switch expr.(type) {
	case *ast.CallExpr, *ast.StringInterpExpr, *ast.StructInitExpr, *ast.ArrayLitExpr, *ast.BinaryExpr:
		return true
	}
	return false
}

func (g *Generator) emitStmt(out *strings.Builder, stmt ast.Stmt, indent string, fnRet checker.Type) {
	switch s := stmt.(type) {
	case *ast.VarDeclStmt:
		if s.Name.Name == "_" {
			if detached, ok := g.tryEmitDetachedActorSend(s.Value); ok {
				out.WriteString(fmt.Sprintf("%s%s;\n", indent, detached))
				return
			}
			if call, ok := s.Value.(*ast.CallExpr); ok && call.OrBlock != nil {
				valType := g.chk.ExprTypes[s.Value]
				g.emitUnwrappedCall(out, "", valType, false, call, indent, fnRet)
				return
			}
			valType := g.chk.ExprTypes[s.Value]
			if isFreshOwningRValue(s.Value) && g.typeOwnsHeap(valType) {
				tmpDiscard := g.nextTmp("discard")
				out.WriteString(fmt.Sprintf("%s%s %s = %s;\n", indent, g.cType(valType), tmpDiscard, g.emitExpr(s.Value)))
				g.emitFreeLValueStmt(out, indent, valType, tmpDiscard)
				return
			}
			out.WriteString(fmt.Sprintf("%s(void)(%s);\n", indent, g.emitExpr(s.Value)))
			return
		}

		valType := g.chk.ExprTypes[s.Value]
		if call, ok := s.Value.(*ast.CallExpr); ok && call.OrBlock != nil {
			g.emitUnwrappedCall(out, s.Name.Name, valType, s.IsMut, call, indent, fnRet)
			return
		}

		qual := "const "
		if s.IsMut || g.needsMutableAddressForCleanup(valType) {
			qual = ""
		}
		out.WriteString(fmt.Sprintf("%s%s%s %s = %s;\n",
			indent, qual, g.cType(valType), s.Name.Name, g.emitExpr(s.Value)))
		if !g.inMainFn && g.fnDeferVarNames[s.Name.Name] {
			if fnExpr := g.typeDeferFreeFn(valType); fnExpr != "" {
				out.WriteString(fmt.Sprintf("%s_vira_actor_defer_push(%s, &%s);\n", indent, fnExpr, s.Name.Name))
			}
		}

	case *ast.AssignStmt:
		if ident, ok := s.Target.(*ast.IdentExpr); ok && ident.Ident.Name == "_" {
			if detached, ok := g.tryEmitDetachedActorSend(s.Value); ok {
				out.WriteString(fmt.Sprintf("%s%s;\n", indent, detached))
				return
			}
			if call, ok := s.Value.(*ast.CallExpr); ok && call.OrBlock != nil {
				valType := g.chk.ExprTypes[s.Value]
				g.emitUnwrappedCall(out, "", valType, false, call, indent, fnRet)
				return
			}
			valType := g.chk.ExprTypes[s.Value]
			if isFreshOwningRValue(s.Value) && g.typeOwnsHeap(valType) {
				tmpDiscard := g.nextTmp("discard")
				out.WriteString(fmt.Sprintf("%s%s %s = %s;\n", indent, g.cType(valType), tmpDiscard, g.emitExpr(s.Value)))
				g.emitFreeLValueStmt(out, indent, valType, tmpDiscard)
				return
			}
			out.WriteString(fmt.Sprintf("%s(void)(%s);\n", indent, g.emitExpr(s.Value)))
			return
		}
		if idxExpr, isIdx := s.Target.(*ast.IndexExpr); isIdx {
			leftType := g.chk.ExprTypes[idxExpr.Left]
			lenExpr := fmt.Sprintf("%s.len", g.emitLValue(idxExpr.Left))
			if ident, ok := idxExpr.Left.(*ast.IdentExpr); ok && g.isPointerReceiverVar(ident.Ident.Name) {
				lenExpr = fmt.Sprintf("%s->len", g.emitLValue(idxExpr.Left))
			}
			if arr, ok := leftType.(*checker.ArrayType); ok {
				lenExpr = fmt.Sprintf("%d", arr.Len)
			}
			out.WriteString(fmt.Sprintf("%svira_bounds_check(%s, %s, __FILE__, __LINE__);\n",
				indent, g.emitExpr(idxExpr.Index), lenExpr))
			if elemType := g.chk.ExprTypes[s.Target]; elemType != nil && elemType.Equals(checker.TypeString) {
				out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.emitLValue(s.Target)))
			}
		}
		if call, ok := s.Value.(*ast.CallExpr); ok && call.OrBlock != nil {
			targetLValue := g.emitLValue(s.Target)
			valType := g.chk.ExprTypes[s.Value]
			g.emitUnwrappedAssign(out, targetLValue, valType, call, indent, fnRet)
			return
		}
		rhsExpr := g.emitExpr(s.Value)
		if ident, ok := s.Value.(*ast.IdentExpr); ok && g.isPointerReceiverVar(ident.Ident.Name) {
			targetType := g.chk.ExprTypes[s.Target]
			if _, isStruct := targetType.(*checker.StructType); isStruct {
				rhsExpr = "*" + rhsExpr
			}
		}
		targetLValue := g.emitLValue(s.Target)
		targetType := g.chk.ExprTypes[s.Target]
		if _, isIdx := s.Target.(*ast.IndexExpr); !isIdx {
			if targetType != nil && targetType.Equals(checker.TypeString) && s.Op == token.TokAssign {
				tmpOld := g.nextTmp("old_str")
				out.WriteString(fmt.Sprintf("%svira_string %s = %s;\n", indent, tmpOld, targetLValue))
				out.WriteString(fmt.Sprintf("%s%s = %s;\n", indent, targetLValue, rhsExpr))
				out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, tmpOld))
				return
			}
		}
		opStr := s.Op.String()
		out.WriteString(fmt.Sprintf("%s%s %s %s;\n",
			indent, targetLValue, opStr, rhsExpr))

	case *ast.IfStmt:
		out.WriteString(fmt.Sprintf("%sif (%s) {\n", indent, g.emitExpr(s.Cond)))
		g.emitBlockStmts(out, s.Then, indent+"    ", fnRet)
		if s.Else != nil {
			if len(s.Else.Stmts) == 1 {
				if nestedIf, ok := s.Else.Stmts[0].(*ast.IfStmt); ok {
					out.WriteString(fmt.Sprintf("%s} else ", indent))
					g.emitStmt(out, nestedIf, indent, fnRet)
					return
				}
			}
			out.WriteString(fmt.Sprintf("%s} else {\n", indent))
			g.emitBlockStmts(out, s.Else, indent+"    ", fnRet)
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case *ast.SwitchStmt:
		g.emitSwitchStmt(out, s, indent, fnRet)

	case *ast.ForStmt:
		g.loopDepth++
		if s.Init != nil {
			out.WriteString(fmt.Sprintf("%s{\n", indent))
			g.emitStmt(out, s.Init, indent+"    ", fnRet)
			condStr := "1"
			if s.Cond != nil {
				condStr = g.emitExpr(s.Cond)
			}
			postStr := ""
			if s.Post != nil {
				if assign, ok := s.Post.(*ast.AssignStmt); ok {
					postStr = fmt.Sprintf("%s %s %s", g.emitLValue(assign.Target), assign.Op.String(), g.emitExpr(assign.Value))
				} else if exprStmt, ok := s.Post.(*ast.ExprStmt); ok {
					postStr = g.emitExpr(exprStmt.Expr)
				}
			}
			out.WriteString(fmt.Sprintf("%s    for (; %s; %s) {\n", indent, condStr, postStr))
			g.emitBlockStmts(out, s.Body, indent+"        ", fnRet)
			out.WriteString(fmt.Sprintf("%s    }\n", indent))
			out.WriteString(fmt.Sprintf("%s}\n", indent))
		} else if s.Cond != nil {
			out.WriteString(fmt.Sprintf("%swhile (%s) {\n", indent, g.emitExpr(s.Cond)))
			g.emitBlockStmts(out, s.Body, indent+"    ", fnRet)
			out.WriteString(fmt.Sprintf("%s}\n", indent))
		} else {
			out.WriteString(fmt.Sprintf("%sfor (;;) {\n", indent))
			g.emitBlockStmts(out, s.Body, indent+"    ", fnRet)
			out.WriteString(fmt.Sprintf("%s}\n", indent))
		}
		g.loopDepth--

	case *ast.ForInStmt:
		g.loopDepth++
		iterType := g.chk.ExprTypes[s.Iter]
		var elemType checker.Type
		var isFixedArray bool
		var fixedLen int
		if sl, ok := iterType.(*checker.SliceType); ok {
			elemType = sl.Elem
		} else if arr, ok := iterType.(*checker.ArrayType); ok {
			elemType = arr.Elem
			isFixedArray = true
			fixedLen = arr.Len
		} else if iterType != nil && iterType.Equals(checker.TypeString) {
			elemType = checker.TypeString
		}

		tmpIter := g.nextTmp("iter")
		tmpIdx := g.nextTmp("i")
		iterVal := g.emitExpr(s.Iter)
		if ident, ok := s.Iter.(*ast.IdentExpr); ok && g.isPointerReceiverVar(ident.Ident.Name) {
			iterVal = "(*" + ident.Ident.Name + ")"
		}

		out.WriteString(fmt.Sprintf("%s{\n", indent))
		out.WriteString(fmt.Sprintf("%s    %s %s = %s;\n",
			indent, g.cType(iterType), tmpIter, iterVal))

		lenExpr := fmt.Sprintf("%s.len", tmpIter)
		if isFixedArray {
			lenExpr = fmt.Sprintf("%d", fixedLen)
		}
		out.WriteString(fmt.Sprintf("%s    for (int32_t %s = 0; %s < %s; %s++) {\n",
			indent, tmpIdx, tmpIdx, lenExpr, tmpIdx))

		elemExpr := fmt.Sprintf("%s.data[%s]", tmpIter, tmpIdx)
		if iterType != nil && iterType.Equals(checker.TypeString) {
			elemExpr = fmt.Sprintf("vira_str_char_at(%s, %s)", tmpIter, tmpIdx)
		}
		out.WriteString(fmt.Sprintf("%s        %s %s = %s;\n",
			indent, g.cType(elemType), s.Var.Name, elemExpr))

		g.emitBlockStmts(out, s.Body, indent+"        ", fnRet)
		out.WriteString(fmt.Sprintf("%s    }\n", indent))

		if _, isIdent := s.Iter.(*ast.IdentExpr); !isIdent {
			if _, isSlice := iterType.(*checker.SliceType); isSlice {
				out.WriteString(fmt.Sprintf("%s    %s_free(&%s);\n", indent, g.cSliceName(elemType), tmpIter))
			}
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))
		g.loopDepth--

	case *ast.BranchStmt:
		for i := len(g.activeErrVars) - 1; i >= 0; i-- {
			if g.activeErrVars[i].loopDepth == g.loopDepth {
				if !g.inMainFn {
					out.WriteString(fmt.Sprintf("%s_vira_actor_defer_pop(&%s);\n", indent, g.activeErrVars[i].varName))
				}
				out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.activeErrVars[i].varName))
			}
		}
		if s.Tok == token.TokBreak {
			out.WriteString(fmt.Sprintf("%sbreak;\n", indent))
		} else if s.Tok == token.TokContinue {
			out.WriteString(fmt.Sprintf("%scontinue;\n", indent))
		}

	case *ast.ArenaStmt:
		out.WriteString(fmt.Sprintf("%s{\n", indent))
		out.WriteString(fmt.Sprintf("%s    vira_arena %s = vira_arena_init(1024 * 1024); // 1MB high-speed tensor bump slab\n", indent, s.ArenaVar))
		if !g.inMainFn && g.fnDeferVarNames[s.ArenaVar] {
			out.WriteString(fmt.Sprintf("%s    _vira_actor_defer_push_ex((vira_defer_fn)vira_arena_destroy, &%s, true);\n", indent, s.ArenaVar))
		}
		prevArena := g.activeArena
		g.activeArena = "&" + s.ArenaVar
		g.emitBlockStmts(out, s.Body, indent+"    ", fnRet)
		g.activeArena = prevArena
		out.WriteString(fmt.Sprintf("%s}\n", indent))

	case *ast.DeferFreeStmt:
		if !g.inMainFn {
			out.WriteString(fmt.Sprintf("%s_vira_actor_defer_pop(&%s);\n", indent, s.VarName))
		}
		switch s.Kind {
		case ast.CleanupString:
			out.WriteString(fmt.Sprintf("%svira_str_free(&%s); // autofree: %s\n", indent, s.VarName, s.Reason))
		case ast.CleanupTensor:
			out.WriteString(fmt.Sprintf("%svira_tensor_f32_free(&%s); // autofree: %s\n", indent, s.VarName, s.Reason))
		case ast.CleanupStruct, ast.CleanupActor:
			out.WriteString(fmt.Sprintf("%s%s_autofree(&%s); // autofree: %s\n",
				indent, g.cStructName(s.TypeName), s.VarName, s.Reason))
		case ast.CleanupInterface:
			out.WriteString(fmt.Sprintf("%s%s_autofree(&%s); // autofree: %s\n",
				indent, g.cStructName(s.TypeName), s.VarName, s.Reason))
		case ast.CleanupArena:
			out.WriteString(fmt.Sprintf("%svira_arena_destroy(&%s); // autofree: %s\n", indent, s.VarName, s.Reason))
		case ast.CleanupFuture:
			out.WriteString(fmt.Sprintf("%svira_future_free(&%s); // autofree: %s\n", indent, s.VarName, s.Reason))
		case ast.CleanupSlice:
			sliceName := g.cSliceNameFromTypeName(s.TypeName)
			out.WriteString(fmt.Sprintf("%s%s_free(&%s); // autofree: %s\n", indent, sliceName, s.VarName, s.Reason))
		}

	case *ast.ReturnStmt:
		skipErrName := ""
		if ident, ok := s.Value.(*ast.IdentExpr); ok {
			skipErrName = ident.Ident.Name
		}
		if g.inMainFn && s.Value == nil {
			for i := len(g.activeErrVars) - 1; i >= 0; i-- {
				out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.activeErrVars[i].varName))
			}
			out.WriteString(fmt.Sprintf("%svira_report_mem_stats();\n", indent))
			out.WriteString(fmt.Sprintf("%sreturn 0;\n", indent))
			return
		}
		if s.Value == nil {
			for i := len(g.activeErrVars) - 1; i >= 0; i-- {
				out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.activeErrVars[i].varName))
			}
			if g.hasFnDeferBase {
				out.WriteString(fmt.Sprintf("%s_vira_actor_defer_restore(_vira_defer_base);\n", indent))
			}
			out.WriteString(fmt.Sprintf("%sreturn;\n", indent))
			return
		}
		if resRet, ok := fnRet.(*checker.ResultType); ok {
			cRes := g.cResultName(resRet.Inner)
			if call, isCall := s.Value.(*ast.CallExpr); isCall {
				if ident, isId := call.Callee.(*ast.IdentExpr); isId && ident.Ident.Name == "error" {
					if identArg, ok := call.Args[0].Expr.(*ast.IdentExpr); ok {
						skipErrName = identArg.Ident.Name
					}
					errMsg := g.emitExpr(call.Args[0].Expr)
					if len(g.activeErrVars) > 0 || g.hasFnDeferBase {
						tmpErr := g.nextTmp("ret_err")
						out.WriteString(fmt.Sprintf("%svira_string %s = %s;\n", indent, tmpErr, errMsg))
						for i := len(g.activeErrVars) - 1; i >= 0; i-- {
							if g.activeErrVars[i].varName != skipErrName {
								out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.activeErrVars[i].varName))
							}
						}
						if g.hasFnDeferBase {
							out.WriteString(fmt.Sprintf("%s_vira_actor_defer_restore(_vira_defer_base);\n", indent))
						}
						out.WriteString(fmt.Sprintf("%sreturn (%s){ .is_err = true, .err = %s };\n", indent, cRes, tmpErr))
						return
					}
					out.WriteString(fmt.Sprintf("%sreturn (%s){ .is_err = true, .err = %s };\n", indent, cRes, errMsg))
					return
				}
			}
			valExpr := g.emitExpr(s.Value)
			if len(g.activeErrVars) > 0 || g.hasFnDeferBase {
				tmpVal := g.nextTmp("ret_ok")
				out.WriteString(fmt.Sprintf("%s%s %s = %s;\n", indent, g.cType(resRet.Inner), tmpVal, valExpr))
				for i := len(g.activeErrVars) - 1; i >= 0; i-- {
					if g.activeErrVars[i].varName != skipErrName {
						out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.activeErrVars[i].varName))
					}
				}
				if g.hasFnDeferBase {
					out.WriteString(fmt.Sprintf("%s_vira_actor_defer_restore(_vira_defer_base);\n", indent))
				}
				out.WriteString(fmt.Sprintf("%sreturn (%s){ .is_err = false, .val = %s };\n", indent, cRes, tmpVal))
				return
			}
			out.WriteString(fmt.Sprintf("%sreturn (%s){ .is_err = false, .val = %s };\n",
				indent, cRes, valExpr))
			return
		}
		valExpr := g.emitExpr(s.Value)
		if len(g.activeErrVars) > 0 || g.hasFnDeferBase {
			tmpRet := g.nextTmp("ret")
			out.WriteString(fmt.Sprintf("%s%s %s = %s;\n", indent, g.cType(fnRet), tmpRet, valExpr))
			for i := len(g.activeErrVars) - 1; i >= 0; i-- {
				if g.activeErrVars[i].varName != skipErrName {
					out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, g.activeErrVars[i].varName))
				}
			}
			if g.hasFnDeferBase {
				out.WriteString(fmt.Sprintf("%s_vira_actor_defer_restore(_vira_defer_base);\n", indent))
			}
			out.WriteString(fmt.Sprintf("%sreturn %s;\n", indent, tmpRet))
			return
		}
		out.WriteString(fmt.Sprintf("%sreturn %s;\n", indent, valExpr))

	case *ast.ExprStmt:
		if detached, ok := g.tryEmitDetachedActorSend(s.Expr); ok {
			out.WriteString(fmt.Sprintf("%s%s;\n", indent, detached))
			return
		}
		if call, ok := s.Expr.(*ast.CallExpr); ok && call.OrBlock != nil {
			valType := g.chk.ExprTypes[s.Expr]
			g.emitUnwrappedCall(out, "", valType, false, call, indent, fnRet)
			return
		}
		out.WriteString(fmt.Sprintf("%s%s;\n", indent, g.emitExpr(s.Expr)))
	}
}

func (g *Generator) emitSwitchStmt(out *strings.Builder, s *ast.SwitchStmt, indent string, fnRet checker.Type) {
	tagType := checker.Type(nil)
	if s.Tag != nil {
		tagType = g.chk.ExprTypes[s.Tag]
	}

	// 1. String switch: emit if-else if-else chain using vira_str_eq
	if tagType != nil && tagType.Equals(checker.TypeString) {
		tagExpr := g.emitExpr(s.Tag)
		swTmp := g.nextTmp("sw_str")
		out.WriteString(fmt.Sprintf("%s{\n", indent))
		out.WriteString(fmt.Sprintf("%s    vira_string %s = %s;\n", indent, swTmp, tagExpr))

		firstCase := true
		for _, cs := range s.Cases {
			if cs.IsDefault {
				continue
			}
			var conds []string
			for _, expr := range cs.Exprs {
				conds = append(conds, fmt.Sprintf("vira_str_eq(%s, %s)", swTmp, g.emitExpr(expr)))
			}
			condStr := strings.Join(conds, " || ")
			if firstCase {
				out.WriteString(fmt.Sprintf("%s    if (%s) {\n", indent, condStr))
				firstCase = false
			} else {
				out.WriteString(fmt.Sprintf("%s    } else if (%s) {\n", indent, condStr))
			}
			for _, stmt := range cs.Body {
				g.emitStmt(out, stmt, indent+"        ", fnRet)
			}
		}

		// Handle default
		for _, cs := range s.Cases {
			if cs.IsDefault {
				if firstCase {
					out.WriteString(fmt.Sprintf("%s    {\n", indent))
					firstCase = false
				} else {
					out.WriteString(fmt.Sprintf("%s    } else {\n", indent))
				}
				for _, stmt := range cs.Body {
					g.emitStmt(out, stmt, indent+"        ", fnRet)
				}
				break
			}
		}

		if !firstCase {
			out.WriteString(fmt.Sprintf("%s    }\n", indent))
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))
		return
	}

	// 2. Tagless switch: emit if-else if-else chain
	if s.Tag == nil {
		out.WriteString(fmt.Sprintf("%s{\n", indent))
		firstCase := true
		for _, cs := range s.Cases {
			if cs.IsDefault {
				continue
			}
			var conds []string
			for _, expr := range cs.Exprs {
				conds = append(conds, fmt.Sprintf("(%s)", g.emitExpr(expr)))
			}
			condStr := strings.Join(conds, " || ")
			if firstCase {
				out.WriteString(fmt.Sprintf("%s    if (%s) {\n", indent, condStr))
				firstCase = false
			} else {
				out.WriteString(fmt.Sprintf("%s    } else if (%s) {\n", indent, condStr))
			}
			for _, stmt := range cs.Body {
				g.emitStmt(out, stmt, indent+"        ", fnRet)
			}
		}

		// Handle default
		for _, cs := range s.Cases {
			if cs.IsDefault {
				if firstCase {
					out.WriteString(fmt.Sprintf("%s    {\n", indent))
					firstCase = false
				} else {
					out.WriteString(fmt.Sprintf("%s    } else {\n", indent))
				}
				for _, stmt := range cs.Body {
					g.emitStmt(out, stmt, indent+"        ", fnRet)
				}
				break
			}
		}

		if !firstCase {
			out.WriteString(fmt.Sprintf("%s    }\n", indent))
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))
		return
	}

	// 3. Integer/enum/bool switch: emit native C switch
	tagExpr := g.emitExpr(s.Tag)
	out.WriteString(fmt.Sprintf("%sswitch (%s) {\n", indent, tagExpr))
	for _, cs := range s.Cases {
		if cs.IsDefault {
			out.WriteString(fmt.Sprintf("%sdefault: {\n", indent))
		} else {
			for _, expr := range cs.Exprs {
				out.WriteString(fmt.Sprintf("%scase %s:\n", indent, g.emitExpr(expr)))
			}
			out.WriteString(fmt.Sprintf("%s{\n", indent))
		}
		for _, stmt := range cs.Body {
			g.emitStmt(out, stmt, indent+"    ", fnRet)
		}
		hasReturn := false
		if len(cs.Body) > 0 {
			if _, isRet := cs.Body[len(cs.Body)-1].(*ast.ReturnStmt); isRet {
				hasReturn = true
			}
		}
		if !hasReturn {
			out.WriteString(fmt.Sprintf("%s    break;\n", indent))
		}
		out.WriteString(fmt.Sprintf("%s}\n", indent))
	}
	out.WriteString(fmt.Sprintf("%s}\n", indent))
}

func (g *Generator) emitUnwrappedCall(
	out *strings.Builder,
	varName string,
	valType checker.Type,
	isMut bool,
	call *ast.CallExpr,
	indent string,
	fnRet checker.Type,
) {
	tmpRes := g.nextTmp("res")
	cRes := g.cResultName(valType)
	out.WriteString(fmt.Sprintf("%s%s %s = %s;\n", indent, cRes, tmpRes, g.emitRawCall(call)))

	if varName != "" && !valType.Equals(checker.TypeVoid) {
		out.WriteString(fmt.Sprintf("%s%s %s;\n", indent, g.cType(valType), varName))
		out.WriteString(fmt.Sprintf("%smemset(&%s, 0, sizeof(%s));\n", indent, varName, varName))
		_ = isMut
	}

	out.WriteString(fmt.Sprintf("%sif (%s.is_err) {\n", indent, tmpRes))
	out.WriteString(fmt.Sprintf("%s    vira_string err = %s.err;\n", indent, tmpRes))
	out.WriteString(fmt.Sprintf("%s    (void)err;\n", indent))
	if !g.inMainFn {
		out.WriteString(fmt.Sprintf("%s    _vira_actor_defer_push((vira_defer_fn)vira_str_free, &err);\n", indent))
	}

	yieldIdx := len(call.OrBlock.Stmts) - 1
	for yieldIdx >= 0 {
		if _, isDF := call.OrBlock.Stmts[yieldIdx].(*ast.DeferFreeStmt); isDF {
			yieldIdx--
			continue
		}
		break
	}

	g.activeErrVars = append(g.activeErrVars, activeErrScope{varName: "err", loopDepth: g.loopDepth})
	for i, st := range call.OrBlock.Stmts {
		if i == yieldIdx {
			if exprSt, ok := st.(*ast.ExprStmt); ok && varName != "" && !valType.Equals(checker.TypeVoid) {
				isDivergent := false
				if callExpr, isCall := exprSt.Expr.(*ast.CallExpr); isCall {
					if id, isId := callExpr.Callee.(*ast.IdentExpr); isId && (id.Ident.Name == "panic" || id.Ident.Name == "exit") {
						isDivergent = true
					}
				}
				if !isDivergent {
					out.WriteString(fmt.Sprintf("%s    %s = %s;\n", indent, varName, g.emitExpr(exprSt.Expr)))
					continue
				}
			}
		}
		g.emitStmt(out, st, indent+"    ", fnRet)
	}
	g.activeErrVars = g.activeErrVars[:len(g.activeErrVars)-1]

	if !g.inMainFn {
		out.WriteString(fmt.Sprintf("%s    _vira_actor_defer_pop(&err);\n", indent))
	}
	out.WriteString(fmt.Sprintf("%s    vira_str_free(&err);\n", indent))

	if varName != "" && !valType.Equals(checker.TypeVoid) {
		out.WriteString(fmt.Sprintf("%s} else {\n", indent))
		out.WriteString(fmt.Sprintf("%s    %s = %s.val;\n", indent, varName, tmpRes))
	} else if varName == "" && !valType.Equals(checker.TypeVoid) && g.typeOwnsHeap(valType) {
		out.WriteString(fmt.Sprintf("%s} else {\n", indent))
		g.emitFreeLValueStmt(out, indent+"    ", valType, tmpRes+".val")
	}
	out.WriteString(fmt.Sprintf("%s}\n", indent))
	if varName != "" && !valType.Equals(checker.TypeVoid) && !g.inMainFn && g.fnDeferVarNames[varName] {
		if fnExpr := g.typeDeferFreeFn(valType); fnExpr != "" {
			out.WriteString(fmt.Sprintf("%s_vira_actor_defer_push(%s, &%s);\n", indent, fnExpr, varName))
		}
	}
}

func (g *Generator) emitUnwrappedAssign(
	out *strings.Builder,
	targetLValue string,
	valType checker.Type,
	call *ast.CallExpr,
	indent string,
	fnRet checker.Type,
) {
	tmpRes := g.nextTmp("res")
	cRes := g.cResultName(valType)
	out.WriteString(fmt.Sprintf("%s%s %s = %s;\n", indent, cRes, tmpRes, g.emitRawCall(call)))

	out.WriteString(fmt.Sprintf("%sif (%s.is_err) {\n", indent, tmpRes))
	out.WriteString(fmt.Sprintf("%s    vira_string err = %s.err;\n", indent, tmpRes))
	out.WriteString(fmt.Sprintf("%s    (void)err;\n", indent))
	if !g.inMainFn {
		out.WriteString(fmt.Sprintf("%s    _vira_actor_defer_push((vira_defer_fn)vira_str_free, &err);\n", indent))
	}

	yieldIdx := len(call.OrBlock.Stmts) - 1
	for yieldIdx >= 0 {
		if _, isDF := call.OrBlock.Stmts[yieldIdx].(*ast.DeferFreeStmt); isDF {
			yieldIdx--
			continue
		}
		break
	}

	g.activeErrVars = append(g.activeErrVars, activeErrScope{varName: "err", loopDepth: g.loopDepth})
	for i, st := range call.OrBlock.Stmts {
		if i == yieldIdx {
			if exprSt, ok := st.(*ast.ExprStmt); ok && targetLValue != "" && !valType.Equals(checker.TypeVoid) {
				isDivergent := false
				if callExpr, isCall := exprSt.Expr.(*ast.CallExpr); isCall {
					if id, isId := callExpr.Callee.(*ast.IdentExpr); isId && (id.Ident.Name == "panic" || id.Ident.Name == "exit") {
						isDivergent = true
					}
				}
				if !isDivergent {
					if valType.Equals(checker.TypeString) {
						tmpOld := g.nextTmp("old_str")
						out.WriteString(fmt.Sprintf("%s    vira_string %s = %s;\n", indent, tmpOld, targetLValue))
						out.WriteString(fmt.Sprintf("%s    %s = %s;\n", indent, targetLValue, g.emitExpr(exprSt.Expr)))
						out.WriteString(fmt.Sprintf("%s    vira_str_free(&%s);\n", indent, tmpOld))
					} else {
						out.WriteString(fmt.Sprintf("%s    %s = %s;\n", indent, targetLValue, g.emitExpr(exprSt.Expr)))
					}
					continue
				}
			}
		}
		g.emitStmt(out, st, indent+"    ", fnRet)
	}
	g.activeErrVars = g.activeErrVars[:len(g.activeErrVars)-1]

	if !g.inMainFn {
		out.WriteString(fmt.Sprintf("%s    _vira_actor_defer_pop(&err);\n", indent))
	}
	out.WriteString(fmt.Sprintf("%s    vira_str_free(&err);\n", indent))

	if targetLValue != "" && !valType.Equals(checker.TypeVoid) {
		out.WriteString(fmt.Sprintf("%s} else {\n", indent))
		if valType.Equals(checker.TypeString) {
			tmpOld := g.nextTmp("old_str")
			out.WriteString(fmt.Sprintf("%s    vira_string %s = %s;\n", indent, tmpOld, targetLValue))
			out.WriteString(fmt.Sprintf("%s    %s = %s.val;\n", indent, targetLValue, tmpRes))
			out.WriteString(fmt.Sprintf("%s    vira_str_free(&%s);\n", indent, tmpOld))
		} else {
			out.WriteString(fmt.Sprintf("%s    %s = %s.val;\n", indent, targetLValue, tmpRes))
		}
	}
	out.WriteString(fmt.Sprintf("%s}\n", indent))
}

// --- 5. EXPRESSION EMISSION ---

func (g *Generator) emitExpr(expr ast.Expr) string {
	switch e := expr.(type) {
	case *ast.LiteralExpr:
		switch e.Kind {
		case token.TokString:
			return fmt.Sprintf("vira_str_lit(%q, %d)", e.Value, len(e.Value))
		case token.TokInt, token.TokFloat, token.TokTrue, token.TokFalse:
			return strings.ReplaceAll(e.Value, "_", "")
		}

	case *ast.StringInterpExpr:
		return g.emitStringInterp(e)

	case *ast.IdentExpr:
		return e.Ident.Name

	case *ast.StructInitExpr:
		var stName string
		var fullType string
		if ident, ok := e.Type.(*ast.IdentType); ok {
			stName = ident.Name.Name
			fullType = stName
		} else if sel, ok := e.Type.(*ast.SelectorType); ok {
			stName = sel.Name.Name
			fullType = fmt.Sprintf("%s.%s", sel.Pkg.Name, sel.Name.Name)
		}
		var st *checker.StructType
		if expType, ok := g.chk.ExprTypes[e].(*checker.StructType); ok {
			st = expType
		} else {
			st = g.chk.LookupStruct(fullType)
		}
		cSt := g.cStructName(fullType)
		if st != nil && st.Module != "" {
			cSt = fmt.Sprintf("%s__%s", st.Module, st.Name)
		}

		var inits []string
		if st != nil && st.IsActor {
			inits = append(inits, "._ctx = {0}")
		}
		for _, f := range e.Fields {
			valStr := g.emitExpr(f.Value)
			if ident, ok := f.Value.(*ast.IdentExpr); ok && g.isPointerReceiverVar(ident.Ident.Name) {
				if st != nil {
					if finfo, hasField := st.Fields[f.Name.Name]; hasField {
						if _, isStruct := finfo.Type.(*checker.StructType); isStruct {
							valStr = "*" + valStr
						}
					}
					for _, emb := range st.Embeds {
						if emb.Name == f.Name.Name {
							valStr = "*" + valStr
							break
						}
					}
				}
			}
			inits = append(inits, fmt.Sprintf(".%s = %s", f.Name.Name, valStr))
		}
		if st != nil && st.IsActor {
			return g.emitActorInitExpr(st, inits)
		}
		return fmt.Sprintf("(%s){ %s }", cSt, strings.Join(inits, ", "))

	case *ast.SelectorExpr:
		return g.emitLValue(e)

	case *ast.CallExpr:
		return g.emitRawCall(e)

	case *ast.BinaryExpr:
		// Tensor Arithmetic (+, -, @)
		if e.Op == token.TokAt || e.Op == token.TokPlus || e.Op == token.TokMinus {
			leftType := g.chk.ExprTypes[e.Left]
			if _, isTensor := leftType.(*checker.TensorType); isTensor {
				arenaArg := "NULL"
				if g.activeArena != "" {
					arenaArg = g.activeArena
				}
				if e.Op == token.TokAt {
					return fmt.Sprintf("vira_tensor_matmul_f32(%s, %s, %s)",
						arenaArg, g.emitExpr(e.Left), g.emitExpr(e.Right))
				} else if e.Op == token.TokPlus {
					return fmt.Sprintf("vira_tensor_add(%s, %s, %s)",
						arenaArg, g.emitExpr(e.Left), g.emitExpr(e.Right))
				} else if e.Op == token.TokMinus {
					return fmt.Sprintf("vira_tensor_sub(%s, %s, %s)",
						arenaArg, g.emitExpr(e.Left), g.emitExpr(e.Right))
				}
			}
		}
		// String equality comparisons
		if e.Op == token.TokEq || e.Op == token.TokNeq {
			leftType := g.chk.ExprTypes[e.Left]
			if leftType != nil && leftType.Equals(checker.TypeString) {
				if e.Op == token.TokEq {
					return fmt.Sprintf("vira_str_eq(%s, %s)", g.emitExpr(e.Left), g.emitExpr(e.Right))
				}
				return fmt.Sprintf("(!vira_str_eq(%s, %s))", g.emitExpr(e.Left), g.emitExpr(e.Right))
			}
		}
		return fmt.Sprintf("(%s %s %s)", g.emitExpr(e.Left), e.Op.String(), g.emitExpr(e.Right))

	case *ast.UnaryExpr:
		return fmt.Sprintf("(%s%s)", e.Op.String(), g.emitExpr(e.Expr))

	case *ast.IndexExpr:
		leftType := g.chk.ExprTypes[e.Left]
		if leftType != nil && leftType.Equals(checker.TypeString) {
			return fmt.Sprintf("vira_str_char_at(%s, %s)", g.emitExpr(e.Left), g.emitExpr(e.Index))
		}
		lenExpr := fmt.Sprintf("%s.len", g.emitLValue(e.Left))
		if ident, ok := e.Left.(*ast.IdentExpr); ok && g.isPointerReceiverVar(ident.Ident.Name) {
			lenExpr = fmt.Sprintf("%s->len", g.emitLValue(e.Left))
		}
		if arr, ok := leftType.(*checker.ArrayType); ok {
			lenExpr = fmt.Sprintf("%d", arr.Len)
		}
		return fmt.Sprintf("({ vira_bounds_check(%s, %s, __FILE__, __LINE__); %s; })",
			g.emitExpr(e.Index), lenExpr, g.emitLValue(e))

	case *ast.ArrayLitExpr:
		t := g.chk.ExprTypes[e]
		if arr, ok := t.(*checker.ArrayType); ok {
			var elemStrs []string
			for _, el := range e.Elems {
				elemStrs = append(elemStrs, g.emitExpr(el))
			}
			cArr := g.cArrayName(arr)
			if len(elemStrs) == 0 {
				return fmt.Sprintf("(%s){0}", cArr)
			}
			return fmt.Sprintf("(%s){ .data = { %s } }", cArr, strings.Join(elemStrs, ", "))
		}
		if sl, ok := t.(*checker.SliceType); ok {
			cSl := g.cSliceName(sl.Elem)
			if len(e.Elems) == 0 {
				return fmt.Sprintf("%s_new(0)", cSl)
			}
			var stmts []string
			tmp := g.nextTmp("sl")
			stmts = append(stmts, fmt.Sprintf("%s %s = %s_new(%d);", cSl, tmp, cSl, len(e.Elems)))
			for i, el := range e.Elems {
				stmts = append(stmts, fmt.Sprintf("%s.data[%d] = %s;", tmp, i, g.emitExpr(el)))
			}
			stmts = append(stmts, fmt.Sprintf("%s.len = %d;", tmp, len(e.Elems)))
			stmts = append(stmts, tmp+";")
			return fmt.Sprintf("({ %s })", strings.Join(stmts, " "))
		}
	}
	return "0"
}

