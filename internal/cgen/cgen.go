type activeErrScope struct {
	varName   string
	loopDepth int
}

type Generator struct {
	chk          *checker.Checker
	af           *autofree.Analyzer
	mod          string
	currentMod   string
	tmpCounter   int
	activeArena  string          // non-empty inside arena { ... } or actor step
	inMainFn     bool
	curReceiver  string          // current receiver variable name if inside a method
	curPtrParams map[string]bool // current mutable pointer parameter names in fn
	usesGUI      bool            // true if any gui_* builtin is called in the file

	fnDeferVarNames map[string]bool  // variables in current fn that have a DeferFreeStmt
	hasFnDeferBase  bool             // true if current fn emitted _vira_defer_base
	loopDepth       int              // current loop nesting depth
	activeErrVars   []activeErrScope // active `err` strings in enclosing `or { ... }` blocks

	resultTypes  map[string]checker.Type             // C Result name -> Inner Type
	vtablePairs  map[string]vtablePair               // "Struct_Iface" -> pair metadata
	actorSenders map[string]actorMethodDispatchSpec // "Actor_Method" -> supervisor wrapper
	arrayTypes   map[string]*checker.ArrayType      // C Array name -> ArrayType
	sliceTypes   map[string]*checker.SliceType      // C Slice name -> SliceType
}

type vtablePair struct {
	Struct *checker.StructType
	Iface  *checker.InterfaceType
}

type actorMethodDispatchSpec struct {
	Actor  *checker.StructType
	Method *checker.FnSig
}

func sanitizeModName(mod string) string {
	if mod == "" {
		return "main"
	}
	var b strings.Builder
	for i, r := range mod {
		if (r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || r == '_' {
			b.WriteRune(r)
		} else if r >= '0' && r <= '9' {
			if i == 0 {
				b.WriteByte('_')
			}
			b.WriteRune(r)
		} else {
			b.WriteByte('_')
		}
	}
	res := b.String()
	if len(res) == 0 || (res[0] >= '0' && res[0] <= '9') {
		res = "_" + res
	}
	return res
}

func (g *Generator) currentModule() string {
	if g.currentMod != "" {
		return g.currentMod
	}
	if g.mod != "" {
		return g.mod
	}
	return "main"
}

func New(chk *checker.Checker, af *autofree.Analyzer) *Generator {
	cleanMod := sanitizeModName(chk.ModuleName())
	return &Generator{
		chk:          chk,
		af:           af,
		mod:          cleanMod,
		currentMod:   cleanMod,
		resultTypes:  make(map[string]checker.Type),
		vtablePairs:  make(map[string]vtablePair),
		actorSenders: make(map[string]actorMethodDispatchSpec),
		curPtrParams: make(map[string]bool),
		arrayTypes:   make(map[string]*checker.ArrayType),
		sliceTypes:   make(map[string]*checker.SliceType),
	}
}

// UsesGUI reports whether the compiled file invokes any native GUI builtins.
func (g *Generator) UsesGUI() bool {
	return g.usesGUI
}

func (g *Generator) nextTmp(prefix string) string {
	g.tmpCounter++
	return fmt.Sprintf("_%s_%d", prefix, g.tmpCounter)
}

// EmitFile generates a complete, self-contained C99 translation unit for file.
func (g *Generator) EmitFile(file *ast.File) string {
	// Pre-scan AST to discover Result[T] wrappers, (Struct, Interface) vtable pairs, GUI usage, and Actor <- sends
	g.discoverCodegenRequirements(file)

	var out strings.Builder
	out.WriteString("// Generated by Vira Stage-0 C99 Compiler — DO NOT EDIT\n")
	out.WriteString("#include \"vira_rt.h\"\n")
	if g.usesGUI {
		out.WriteString("#include \"vira_gui.h\"\n")
	}
	out.WriteString("\n")

	// 0.5. Emit Fixed Array ([N]T) typedefs
	if len(g.arrayTypes) > 0 {
		out.WriteString("// --- 0.5 FIXED ARRAYS ([N]T) ---\n")
		for cName, arr := range g.arrayTypes {
			out.WriteString(fmt.Sprintf("#ifndef _%s_DEFINED\n#define _%s_DEFINED\n", cName, cName))
			out.WriteString(fmt.Sprintf("typedef struct {\n    %s data[%d];\n} %s;\n#endif\n\n",
				g.cType(arr.Elem), arr.Len, cName))
		}
	}

	// 1. Emit Struct & Actor typedefs + _autofree & _reset helpers in topological dependency order
	out.WriteString("// --- 1. STRUCTS, ACTORS & DETERMINISTIC DESTRUCTORS ---\n")
	for _, decl := range file.Decls {
		if sd, ok := decl.(*ast.StructDecl); ok {
			modName := sd.Module
			if modName == "" {
				modName = g.currentModule()
			}
			cSt := fmt.Sprintf("%s__%s", modName, sd.Name.Name)
			out.WriteString(fmt.Sprintf("typedef struct %s %s;\n", cSt, cSt))
		}
	}
	out.WriteString("\n")
	g.emitStructsTopologically(&out, file)

	// 2. Emit Result_T wrapper structs & Future[T] awaiters
	if len(g.resultTypes) > 0 {
		out.WriteString("// --- 2. RESULT (!T) & ASYNC FUTURE[T] CONTAINERS ---\n")
		for cName, inner := range g.resultTypes {
			out.WriteString(fmt.Sprintf("#ifndef _%s_DEFINED\n#define _%s_DEFINED\n", cName, cName))
			out.WriteString("typedef struct {\n")
			out.WriteString("    bool is_err;\n")
			out.WriteString("    vira_string err;\n")
			if !inner.Equals(checker.TypeVoid) {
				out.WriteString(fmt.Sprintf("    %s val;\n", g.cType(inner)))
			}
			out.WriteString(fmt.Sprintf("} %s;\n#endif\n\n", cName))

			// C99 initial-member header shared by all Future[T] message envelopes returning cName
			out.WriteString("typedef struct {\n")
			out.WriteString("    vira_task _task;\n")
			out.WriteString(fmt.Sprintf("    %s result;\n", cName))
			out.WriteString(fmt.Sprintf("} _FutureHeader_%s;\n\n", cName))

			out.WriteString(fmt.Sprintf("static inline %s Future_%s_await(vira_future* f) {\n", cName, cName))
			out.WriteString("    if (!f || !f->env) {\n")
			out.WriteString(fmt.Sprintf("        return (%s){ .is_err = true, .err = vira_str_lit(\"future already awaited\", 22) };\n", cName))
			out.WriteString("    }\n")
			out.WriteString(fmt.Sprintf("    _FutureHeader_%s* hdr = (_FutureHeader_%s*)f->env;\n", cName, cName))
			out.WriteString("    vira_scheduler_await(&hdr->_task);\n")
			out.WriteString(fmt.Sprintf("    %s res = hdr->result;\n", cName))
			out.WriteString("    free(f->env);\n")
			out.WriteString("    f->env = NULL;\n")
			out.WriteString("    f->task = NULL;\n")
			out.WriteString("    f->drop_fn = NULL;\n")
			out.WriteString("    _vira_record_free();\n")
			out.WriteString("    return res;\n")
			out.WriteString("}\n\n")
		}
	}

	// 3. Emit Fat-Pointer Interfaces
	out.WriteString("// --- 3. FAT-POINTER INTERFACES ---\n")
	for _, decl := range file.Decls {
		if id, ok := decl.(*ast.InterfaceDecl); ok {
			g.emitInterfaceTypedef(&out, id)
		}
	}

	// 4. Emit Function & Method Forward Declarations
	out.WriteString("// --- 4. FUNCTION & METHOD PROTOTYPES ---\n")
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FnDecl); ok && fn.Name.Name != "main" && (fn.Intrinsic == "" || fn.Body != nil) {
			out.WriteString(g.fnSignature(fn) + ";\n")
		}
	}
	out.WriteString("\n")

	// 5. Emit Static VTables & Boxing Constructors for (Struct, Interface) pairs
	if len(g.vtablePairs) > 0 {
		out.WriteString("// --- 5. POLYMORPHIC VTABLES & AUTOFREE HOOKS ---\n")
		for _, pair := range g.vtablePairs {
			g.emitVTableAndBoxer(&out, pair.Struct, pair.Iface)
		}
	}

	// 6. Emit Supervised Actor Message Wrappers
	if len(g.actorSenders) > 0 {
		out.WriteString("// --- 6. SUPERVISED ACTOR FAULT-ISOLATION WRAPPERS ---\n")
		for _, spec := range g.actorSenders {
			g.emitActorSupervisorWrapper(&out, spec.Actor, spec.Method)
		}
	}

	// 7. Emit Function & Method Bodies
	out.WriteString("// --- 7. FUNCTION & METHOD IMPLEMENTATIONS ---\n")
	for _, decl := range file.Decls {
		if fn, ok := decl.(*ast.FnDecl); ok {
			g.emitFnDecl(&out, fn)
		}
	}

	return out.String()
}

// --- PRE-PASS: DISCOVER RESULTS, VTABLES, GUI USAGE & ACTOR DISPATCHES ---

func (g *Generator) discoverCodegenRequirements(file *ast.File) {
	for _, st := range g.chk.Structs() {
		for _, f := range st.Fields {
			if arr, ok := f.Type.(*checker.ArrayType); ok {
				g.arrayTypes[g.cArrayName(arr)] = arr
			} else if sl, ok := f.Type.(*checker.SliceType); ok {
				g.sliceTypes[g.cSliceName(sl.Elem)] = sl
			}
		}
	}
	for _, decl := range file.Decls {
		fn, ok := decl.(*ast.FnDecl)
		if !ok {
			continue
		}
		if fn.ReturnType != nil {
			retType := g.resolveCheckType(fn)
			if res, isRes := retType.(*checker.ResultType); isRes {
				g.resultTypes[g.cResultName(res.Inner)] = res.Inner
			}
			if arr, ok := retType.(*checker.ArrayType); ok {
				g.arrayTypes[g.cArrayName(arr)] = arr
			} else if sl, ok := retType.(*checker.SliceType); ok {
				g.sliceTypes[g.cSliceName(sl.Elem)] = sl
			}
		}
		for _, p := range fn.Params {
			pt := g.resolveParamType(fn, p.Name.Name)
			if arr, ok := pt.(*checker.ArrayType); ok {
				g.arrayTypes[g.cArrayName(arr)] = arr
			} else if sl, ok := pt.(*checker.SliceType); ok {
				g.sliceTypes[g.cSliceName(sl.Elem)] = sl
			}
		}
		g.scanBlockRequirements(fn.Body)
	}
}

func (g *Generator) scanBlockRequirements(b *ast.BlockStmt) {
	if b == nil {
		return
	}
	for _, stmt := range b.Stmts {
		switch s := stmt.(type) {
		case *ast.VarDeclStmt:
			g.scanExprRequirements(s.Value)
		case *ast.AssignStmt:
			g.scanExprRequirements(s.Value)
		case *ast.ReturnStmt:
			g.scanExprRequirements(s.Value)
		case *ast.IfStmt:
			g.scanExprRequirements(s.Cond)
			g.scanBlockRequirements(s.Then)
			g.scanBlockRequirements(s.Else)
		case *ast.ForStmt:
			if s.Init != nil {
				g.scanBlockRequirements(&ast.BlockStmt{Stmts: []ast.Stmt{s.Init}})
			}
			g.scanExprRequirements(s.Cond)
			if s.Post != nil {
				g.scanBlockRequirements(&ast.BlockStmt{Stmts: []ast.Stmt{s.Post}})
			}
			g.scanBlockRequirements(s.Body)
		case *ast.ForInStmt:
			t := g.chk.ExprTypes[s.Iter]
			if arr, ok := t.(*checker.ArrayType); ok {
				g.arrayTypes[g.cArrayName(arr)] = arr
			} else if sl, ok := t.(*checker.SliceType); ok {
				g.sliceTypes[g.cSliceName(sl.Elem)] = sl
			}
			g.scanExprRequirements(s.Iter)
			g.scanBlockRequirements(s.Body)
		case *ast.ArenaStmt:
			g.scanBlockRequirements(s.Body)
		case *ast.ExprStmt:
			g.scanExprRequirements(s.Expr)
		}
	}
}

func (g *Generator) scanExprRequirements(expr ast.Expr) {
	if expr == nil {
		return
	}
	switch e := expr.(type) {
	case *ast.UnaryExpr:
		g.scanExprRequirements(e.Expr)
	case *ast.IndexExpr:
		t := g.chk.ExprTypes[e.Left]
		if arr, ok := t.(*checker.ArrayType); ok {
			g.arrayTypes[g.cArrayName(arr)] = arr
		} else if sl, ok := t.(*checker.SliceType); ok {
			g.sliceTypes[g.cSliceName(sl.Elem)] = sl
		}
		g.scanExprRequirements(e.Left)
		g.scanExprRequirements(e.Index)
	case *ast.ArrayLitExpr:
		t := g.chk.ExprTypes[e]
		if arr, ok := t.(*checker.ArrayType); ok {
			g.arrayTypes[g.cArrayName(arr)] = arr
		} else if sl, ok := t.(*checker.SliceType); ok {
			g.sliceTypes[g.cSliceName(sl.Elem)] = sl
		}
		for _, el := range e.Elems {
			g.scanExprRequirements(el)
		}
	case *ast.CallExpr:
		if ident, ok := e.Callee.(*ast.IdentExpr); ok {
			// Detect GUI builtin usage so #include "vira_gui.h" is emitted automatically
			if strings.HasPrefix(ident.Ident.Name, "gui_") {
				g.usesGUI = true
			}
			// 1. Interface cast Payable(inv)
			if iface, isIface := g.chk.Interfaces()[ident.Ident.Name]; isIface && len(e.Args) == 1 {
				if st, ok := g.chk.ExprTypes[e.Args[0].Expr].(*checker.StructType); ok {
					key := st.Name + "_" + iface.Name
					g.vtablePairs[key] = vtablePair{Struct: st, Iface: iface}
				}
			}
		}
		if sel, ok := e.Callee.(*ast.SelectorExpr); ok {
			recvType := g.chk.ExprTypes[sel.Left]
			if sl, ok := recvType.(*checker.SliceType); ok {
				g.sliceTypes[g.cSliceName(sl.Elem)] = sl
				if sel.Field.Name == "get" {
					g.resultTypes[g.cResultName(sl.Elem)] = sl.Elem
				}
			} else if arr, ok := recvType.(*checker.ArrayType); ok {
				g.arrayTypes[g.cArrayName(arr)] = arr
				if sel.Field.Name == "get" {
					g.resultTypes[g.cResultName(arr.Elem)] = arr.Elem
				}
			} else if recvType != nil && recvType.Equals(checker.TypeString) {
				switch sel.Field.Name {
				case "split":
					g.sliceTypes[g.cSliceName(checker.TypeString)] = &checker.SliceType{Elem: checker.TypeString}
				case "bytes", "to_bytes":
					g.sliceTypes[g.cSliceName(checker.TypeU8)] = &checker.SliceType{Elem: checker.TypeU8}
				case "to_int":
					g.resultTypes[g.cResultName(checker.TypeInt)] = checker.TypeInt
				case "to_i64":
					g.resultTypes[g.cResultName(checker.TypeI64)] = checker.TypeI64
				}
			}
		}
		// 2. Actor message send worker <- predict(...)
		if sel, ok := e.Callee.(*ast.SelectorExpr); ok && sel.IsActorSend {
			if st, ok := g.chk.ExprTypes[sel.Left].(*checker.StructType); ok && st.IsActor {
				if m, _, _ := st.LookupMethod(sel.Field.Name); m != nil {
					key := st.Name + "_" + m.Name
					g.actorSenders[key] = actorMethodDispatchSpec{Actor: st, Method: m}
					inner := m.ReturnType
					if res, isRes := inner.(*checker.ResultType); isRes {
						inner = res.Inner
					}
					g.resultTypes[g.cResultName(inner)] = inner
				}
			}
		}
		// 3. Method call .await() on Future[T]
		if sel, ok := e.Callee.(*ast.SelectorExpr); ok && sel.Field.Name == "await" {
			if futType, ok := g.chk.ExprTypes[sel.Left].(*checker.FutureType); ok {
				g.resultTypes[g.cResultName(futType.Inner)] = futType.Inner
			}
		}
		// 4. Standard Result return with or-block
		if e.OrBlock != nil {
			inner := g.chk.ExprTypes[e]
			g.resultTypes[g.cResultName(inner)] = inner
			g.scanBlockRequirements(e.OrBlock)
		}
		for _, arg := range e.Args {
			g.scanExprRequirements(arg.Expr)
		}
	case *ast.BinaryExpr:
		g.scanExprRequirements(e.Left)
		g.scanExprRequirements(e.Right)
	}
}

// --- 1. TOPOLOGICAL STRUCT, ACTOR & DETERMINISTIC _autofree GENERATION ---

func (g *Generator) emitStructsTopologically(out *strings.Builder, file *ast.File) {
	declMap := make(map[string]*ast.StructDecl)
	var declOrder []string

	for _, decl := range file.Decls {
		if sd, ok := decl.(*ast.StructDecl); ok {
			modName := sd.Module
			if modName == "" {
				modName = g.currentModule()
			}
			cName := fmt.Sprintf("%s__%s", modName, sd.Name.Name)
			declMap[cName] = sd
			declOrder = append(declOrder, cName)
		}
	}

	emitted := make(map[string]bool)
	var visit func(cName string)
	visit = func(cName string) {
		if emitted[cName] {
			return
		}
		emitted[cName] = true
		sd := declMap[cName]
		if sd == nil {
			return
		}
		st := g.chk.LookupStructInModule(sd.Module, sd.Name.Name)
		if st == nil {
			st = g.chk.LookupStruct(sd.Name.Name)
		}
		if st == nil {
			return
		}
		// Emit embedded and nested value-struct dependencies first
		for _, emb := range st.Embeds {
			embMod := emb.Module
			if embMod == "" {
				embMod = sd.Module
			}
			visit(fmt.Sprintf("%s__%s", embMod, emb.Name))
		}
		for _, fname := range st.FieldOrder {
			if subSt, isSt := st.Fields[fname].Type.(*checker.StructType); isSt {
				subMod := subSt.Module
				if subMod == "" {
					subMod = sd.Module
				}
				visit(fmt.Sprintf("%s__%s", subMod, subSt.Name))
			}
			if sl, isSl := st.Fields[fname].Type.(*checker.SliceType); isSl {
				if elemSt, isElemSt := sl.Elem.(*checker.StructType); isElemSt {
					elemMod := elemSt.Module
					if elemMod == "" {
						elemMod = sd.Module
					}
					visit(fmt.Sprintf("%s__%s", elemMod, elemSt.Name))
				}
			}
		}
		g.emitStructAndDestructor(out, sd)
	}

	for _, cName := range declOrder {
		visit(cName)
	}
}

func (g *Generator) emitStructAndDestructor(out *strings.Builder, sd *ast.StructDecl) {
	st := g.chk.LookupStructInModule(sd.Module, sd.Name.Name)
	if st == nil {
		st = g.chk.LookupStruct(sd.Name.Name)
	}
	if st == nil {
		return
	}
	cStructName := fmt.Sprintf("%s__%s", st.Module, st.Name)
	if st.Module == "" {
		cStructName = g.cStructName(st.Name)
	}

	out.WriteString(fmt.Sprintf("typedef struct %s {\n", cStructName))
	if st.IsActor {
		out.WriteString("    vira_actor_ctx _ctx;\n")
	}
	for _, emb := range st.Embeds {
		cEmb := fmt.Sprintf("%s__%s", emb.Module, emb.Name)
		if emb.Module == "" {
			cEmb = g.cStructName(emb.Name)
		}
		out.WriteString(fmt.Sprintf("    %s %s;\n", cEmb, emb.Name))
	}
	for _, fname := range st.FieldOrder {
		finfo := st.Fields[fname]
		out.WriteString(fmt.Sprintf("    %s %s;\n", g.cType(finfo.Type), fname))
	}
	out.WriteString(fmt.Sprintf("} %s;\n\n", cStructName))

	// If this is an Actor, emit a default state reset function for Supervisor OneForOne restarts
	if st.IsActor {
		out.WriteString(fmt.Sprintf("static inline void %s_supervisor_reset(%s* self) {\n", cStructName, cStructName))
		defaultExprs := make(map[string]ast.Expr)
		for _, f := range sd.Fields {
			if f.DefaultExpr != nil {
				defaultExprs[f.Name.Name] = f.DefaultExpr
			}
		}
		for _, fname := range st.FieldOrder {
			f := st.Fields[fname]
			if f.Type.Equals(checker.TypeString) {
				out.WriteString(fmt.Sprintf("    vira_str_free(&self->%s);\n", fname))
			} else if _, isTensor := f.Type.(*checker.TensorType); isTensor {
				out.WriteString(fmt.Sprintf("    vira_tensor_f32_free(&self->%s);\n", fname))
			} else if sl, isSl := f.Type.(*checker.SliceType); isSl {
				out.WriteString(fmt.Sprintf("    %s_free(&self->%s);\n", g.cSliceName(sl.Elem), fname))
			} else if subSt, isSt := f.Type.(*checker.StructType); isSt && g.af.StructTypeNeedsFree(subSt) {
				cSub := fmt.Sprintf("%s__%s", subSt.Module, subSt.Name)
				if subSt.Module == "" {
					cSub = g.cStructName(subSt.Name)
				}
				out.WriteString(fmt.Sprintf("    %s_autofree(&self->%s);\n", cSub, fname))
			}
			if defExpr, hasDef := defaultExprs[fname]; hasDef {
				out.WriteString(fmt.Sprintf("    self->%s = %s;\n", fname, g.emitExpr(defExpr)))
			}
		}
		out.WriteString("}\n\n")

		out.WriteString(fmt.Sprintf("static inline void %s_autofree(%s* self) {\n", cStructName, cStructName))
		out.WriteString("    if (!self) return;\n")
		out.WriteString("    vira_actor_ctx_destroy(&self->_ctx);\n")
		for _, fname := range st.FieldOrder {
			f := st.Fields[fname]
			if f.Type.Equals(checker.TypeString) {
				out.WriteString(fmt.Sprintf("    vira_str_free(&self->%s);\n", fname))
			} else if _, isTensor := f.Type.(*checker.TensorType); isTensor {
				out.WriteString(fmt.Sprintf("    vira_tensor_f32_free(&self->%s);\n", fname))
			} else if sl, isSl := f.Type.(*checker.SliceType); isSl {
				out.WriteString(fmt.Sprintf("    %s_free(&self->%s);\n", g.cSliceName(sl.Elem), fname))
			} else if subSt, isSt := f.Type.(*checker.StructType); isSt && g.af.StructTypeNeedsFree(subSt) {
				cSub := fmt.Sprintf("%s__%s", subSt.Module, subSt.Name)
				if subSt.Module == "" {
					cSub = g.cStructName(subSt.Name)
				}
				out.WriteString(fmt.Sprintf("    %s_autofree(&self->%s);\n", cSub, fname))
			}
		}
		out.WriteString("}\n\n")
		g.emitStructSliceDefinition(out, st, cStructName)
		return
	}

	// Emit deterministic _autofree and _clone functions if the struct transitively owns heap fields
	if g.af.StructTypeNeedsFree(st) {
		out.WriteString(fmt.Sprintf("static inline void %s_autofree(%s* self) {\n", cStructName, cStructName))
		out.WriteString("    if (!self) return;\n")
		for _, emb := range st.Embeds {
			if g.af.StructTypeNeedsFree(emb) {
				cEmb := fmt.Sprintf("%s__%s", emb.Module, emb.Name)
				if emb.Module == "" {
					cEmb = g.cStructName(emb.Name)
				}
				out.WriteString(fmt.Sprintf("    %s_autofree(&self->%s);\n", cEmb, emb.Name))
			}
		}
		for _, fname := range st.FieldOrder {
			finfo := st.Fields[fname]
			if finfo.Type.Equals(checker.TypeString) {
				out.WriteString(fmt.Sprintf("    vira_str_free(&self->%s);\n", fname))
			} else if _, isTensor := finfo.Type.(*checker.TensorType); isTensor {
				out.WriteString(fmt.Sprintf("    vira_tensor_f32_free(&self->%s);\n", fname))
			} else if sl, isSl := finfo.Type.(*checker.SliceType); isSl {
				out.WriteString(fmt.Sprintf("    %s_free(&self->%s);\n", g.cSliceName(sl.Elem), fname))
			} else if subSt, isSt := finfo.Type.(*checker.StructType); isSt && g.af.StructTypeNeedsFree(subSt) {
				cSub := fmt.Sprintf("%s__%s", subSt.Module, subSt.Name)
				if subSt.Module == "" {
					cSub = g.cStructName(subSt.Name)
				}
				out.WriteString(fmt.Sprintf("    %s_autofree(&self->%s);\n", cSub, fname))
			}
		}
		out.WriteString("}\n\n")

		out.WriteString(fmt.Sprintf("static inline %s %s_clone(const %s* self) {\n", cStructName, cStructName, cStructName))
		out.WriteString(fmt.Sprintf("    %s copy = *self;\n", cStructName))
		for _, emb := range st.Embeds {
			if g.af.StructTypeNeedsFree(emb) && !emb.IsActor {
				cEmb := fmt.Sprintf("%s__%s", emb.Module, emb.Name)
				if emb.Module == "" {
					cEmb = g.cStructName(emb.Name)
				}
				out.WriteString(fmt.Sprintf("    copy.%s = %s_clone(&self->%s);\n", emb.Name, cEmb, emb.Name))
			}
		}
		for _, fname := range st.FieldOrder {
			finfo := st.Fields[fname]
			if finfo.Type.Equals(checker.TypeString) {
				out.WriteString(fmt.Sprintf("    copy.%s = vira_str_clone(self->%s);\n", fname, fname))
			} else if _, isTensor := finfo.Type.(*checker.TensorType); isTensor {
				out.WriteString(fmt.Sprintf("    copy.%s = vira_tensor_f32_clone(self->%s);\n", fname, fname))
			} else if sl, isSl := finfo.Type.(*checker.SliceType); isSl {
				out.WriteString(fmt.Sprintf("    copy.%s = %s_clone(&self->%s);\n", fname, g.cSliceName(sl.Elem), fname))
			} else if subSt, isSt := finfo.Type.(*checker.StructType); isSt && !subSt.IsActor && g.af.StructTypeNeedsFree(subSt) {
				cSub := fmt.Sprintf("%s__%s", subSt.Module, subSt.Name)
				if subSt.Module == "" {
					cSub = g.cStructName(subSt.Name)
				}
				out.WriteString(fmt.Sprintf("    copy.%s = %s_clone(&self->%s);\n", fname, cSub, fname))
			}
		}
		out.WriteString("    return copy;\n")
		out.WriteString("}\n\n")
	}
	g.emitStructSliceDefinition(out, st, cStructName)
}

func (g *Generator) emitStructSliceDefinition(out *strings.Builder, st *checker.StructType, cStructName string) {
	needsFree := g.af.StructTypeNeedsFree(st)
	out.WriteString(fmt.Sprintf("#ifndef _vira_slice_%s_DEFINED\n#define _vira_slice_%s_DEFINED\n", cStructName, cStructName))
	out.WriteString(fmt.Sprintf("typedef struct {\n"))
	out.WriteString(fmt.Sprintf("    %s*     data;\n", cStructName))
	out.WriteString(fmt.Sprintf("    int32_t len;\n"))
	out.WriteString(fmt.Sprintf("    int32_t cap;\n"))
	out.WriteString(fmt.Sprintf("    bool    is_arena;\n"))
	out.WriteString(fmt.Sprintf("} vira_slice_%s;\n\n", cStructName))

	out.WriteString(fmt.Sprintf("static inline vira_slice_%s vira_slice_%s_new(int32_t initial_cap) {\n", cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    vira_slice_%s s = { .data = NULL, .len = 0, .cap = 0, .is_arena = false };\n", cStructName))
	out.WriteString(fmt.Sprintf("    if (initial_cap > 0) {\n"))
	out.WriteString(fmt.Sprintf("        s.data = (%s*)malloc((size_t)initial_cap * sizeof(%s));\n", cStructName, cStructName))
	out.WriteString(fmt.Sprintf("        if (s.data) { s.cap = initial_cap; _vira_record_alloc(); }\n"))
	out.WriteString(fmt.Sprintf("    }\n"))
	out.WriteString(fmt.Sprintf("    return s;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline void vira_slice_%s_push(vira_slice_%s* s, %s val) {\n", cStructName, cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    if (s->len >= s->cap) {\n"))
	out.WriteString(fmt.Sprintf("        _vira_slice_grow((void**)&s->data, &s->cap, sizeof(%s), s->is_arena);\n", cStructName))
	out.WriteString(fmt.Sprintf("    }\n"))
	out.WriteString(fmt.Sprintf("    s->data[s->len++] = val;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline %s vira_slice_%s_pop(vira_slice_%s* s) {\n", cStructName, cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    if (s->len <= 0) {\n"))
	out.WriteString(fmt.Sprintf("        fprintf(stderr, \"vira panic: pop from empty slice\\n\");\n"))
	out.WriteString(fmt.Sprintf("        exit(1);\n"))
	out.WriteString(fmt.Sprintf("    }\n"))
	out.WriteString(fmt.Sprintf("    return s->data[--s->len];\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline void vira_slice_%s_set(vira_slice_%s* s, int32_t idx, %s val) {\n", cStructName, cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    vira_bounds_check(idx, s->len, __FILE__, __LINE__);\n"))
	if needsFree {
		out.WriteString(fmt.Sprintf("    %s_autofree(&s->data[idx]);\n", cStructName))
	}
	out.WriteString(fmt.Sprintf("    s->data[idx] = val;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline void vira_slice_%s_clear(vira_slice_%s* s) {\n", cStructName, cStructName))
	if needsFree {
		out.WriteString(fmt.Sprintf("    for (int32_t i = 0; i < s->len; i++) {\n"))
		out.WriteString(fmt.Sprintf("        %s_autofree(&s->data[i]);\n", cStructName))
		out.WriteString(fmt.Sprintf("    }\n"))
	}
	out.WriteString(fmt.Sprintf("    s->len = 0;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline bool vira_slice_%s_is_empty(const vira_slice_%s* s) {\n", cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    return s->len == 0;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline vira_slice_%s vira_slice_%s_clone(const vira_slice_%s* s) {\n", cStructName, cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    vira_slice_%s res = vira_slice_%s_new(s->len);\n", cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    if (s->len > 0 && s->data != NULL) {\n"))
	if needsFree && !st.IsActor {
		out.WriteString(fmt.Sprintf("        for (int32_t i = 0; i < s->len; i++) {\n"))
		out.WriteString(fmt.Sprintf("            res.data[i] = %s_clone(&s->data[i]);\n", cStructName))
		out.WriteString(fmt.Sprintf("        }\n"))
		out.WriteString(fmt.Sprintf("        res.len = s->len;\n"))
	} else {
		out.WriteString(fmt.Sprintf("        memcpy(res.data, s->data, (size_t)s->len * sizeof(%s));\n", cStructName))
		out.WriteString(fmt.Sprintf("        res.len = s->len;\n"))
	}
	out.WriteString(fmt.Sprintf("    }\n"))
	out.WriteString(fmt.Sprintf("    return res;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline bool vira_slice_%s_contains(const vira_slice_%s* s, %s val) {\n", cStructName, cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    for (int32_t i = 0; i < s->len; i++) {\n"))
	out.WriteString(fmt.Sprintf("        if (memcmp(&s->data[i], &val, sizeof(%s)) == 0) return true;\n", cStructName))
	out.WriteString(fmt.Sprintf("    }\n"))
	out.WriteString(fmt.Sprintf("    return false;\n"))
	out.WriteString(fmt.Sprintf("}\n\n"))

	out.WriteString(fmt.Sprintf("static inline void vira_slice_%s_free(vira_slice_%s* s) {\n", cStructName, cStructName))
	out.WriteString(fmt.Sprintf("    if (s->data != NULL && !s->is_arena) {\n"))
	if needsFree {
		out.WriteString(fmt.Sprintf("        for (int32_t i = 0; i < s->len; i++) {\n"))
		out.WriteString(fmt.Sprintf("            %s_autofree(&s->data[i]);\n", cStructName))
		out.WriteString(fmt.Sprintf("        }\n"))
	}
	out.WriteString(fmt.Sprintf("        _vira_slice_free_raw((void**)&s->data, &s->len, &s->cap, s->is_arena);\n"))
	out.WriteString(fmt.Sprintf("    }\n"))
	out.WriteString(fmt.Sprintf("}\n#endif\n\n"))
}

// --- 2. INTERFACES & STATIC VTABLES ---

func (g *Generator) emitInterfaceTypedef(out *strings.Builder, id *ast.InterfaceDecl) {
	iface := g.chk.Interfaces()[id.Name.Name]
	cIface := g.cStructName(iface.Name)

	out.WriteString(fmt.Sprintf("typedef struct %s_vtable {\n", cIface))
	for _, m := range id.Methods {
		msig := iface.Methods[m.Name.Name]
		retStr := g.cType(msig.ReturnType)
		selfQual := "const void*"
		if msig.IsMutReceiver {
			selfQual = "void*"
		}
		var ptypes []string
		ptypes = append(ptypes, selfQual+" _self")
		for _, p := range msig.Params {
			ptypes = append(ptypes, fmt.Sprintf("%s %s", g.cType(p.Type), p.Name))
		}
		out.WriteString(fmt.Sprintf("    %s (*%s)(%s);\n", retStr, m.Name.Name, strings.Join(ptypes, ", ")))
	}
	out.WriteString("    void (*_autofree)(void* _self);\n")
	out.WriteString(fmt.Sprintf("} %s_vtable;\n\n", cIface))

	out.WriteString(fmt.Sprintf("typedef struct %s {\n", cIface))
	out.WriteString("    void* _object;\n")
	out.WriteString(fmt.Sprintf("    const %s_vtable* _vtable;\n", cIface))
	out.WriteString(fmt.Sprintf("} %s;\n\n", cIface))

	out.WriteString(fmt.Sprintf("static inline void %s_autofree(%s* self) {\n", cIface, cIface))
	out.WriteString("    if (self && self->_vtable && self->_vtable->_autofree && self->_object) {\n")
	out.WriteString("        self->_vtable->_autofree(self->_object);\n")
	out.WriteString("        self->_object = NULL;\n")
	out.WriteString("    }\n")
	out.WriteString("}\n\n")
}

func (g *Generator) emitVTableAndBoxer(out *strings.Builder, st *checker.StructType, iface *checker.InterfaceType) {
	cSt := g.cStructName(st.Name)
	cIf := g.cStructName(iface.Name)

	out.WriteString(fmt.Sprintf("static void _vtable_free_%s_as_%s(void* _obj) {\n", st.Name, iface.Name))
	out.WriteString("    if (!_obj) return;\n")
	if g.af.StructTypeNeedsFree(st) {
		out.WriteString(fmt.Sprintf("    %s_autofree((%s*)_obj);\n", cSt, cSt))
	}
	out.WriteString("    free(_obj);\n")
	out.WriteString("    _vira_record_free();\n")
	out.WriteString("}\n\n")

	out.WriteString(fmt.Sprintf("static const %s_vtable _vtable_%s_for_%s = {\n", cIf, st.Name, iface.Name))
	for mname, msig := range iface.Methods {
		selfQual := "const void*"
		if msig.IsMutReceiver {
			selfQual = "void*"
		}
		var ptypes []string
		ptypes = append(ptypes, selfQual)
		for _, p := range msig.Params {
			ptypes = append(ptypes, g.cType(p.Type))
		}
		selfCast := fmt.Sprintf("(%s (*)(%s))", g.cType(msig.ReturnType), strings.Join(ptypes, ", "))
		out.WriteString(fmt.Sprintf("    .%s = %s%s_%s,\n", mname, selfCast, cSt, mname))
	}
	out.WriteString(fmt.Sprintf("    ._autofree = _vtable_free_%s_as_%s,\n", st.Name, iface.Name))
	out.WriteString("};\n\n")

	out.WriteString(fmt.Sprintf("static inline %s %s_box_%s(%s val) {\n", cIf, cIf, st.Name, cSt))
	out.WriteString(fmt.Sprintf("    %s* heap_obj = (%s*)malloc(sizeof(%s));\n", cSt, cSt, cSt))
	out.WriteString("    *heap_obj = val;\n")
	out.WriteString("    _vira_record_alloc();\n")
	out.WriteString(fmt.Sprintf("    return (%s){ ._object = heap_obj, ._vtable = &_vtable_%s_for_%s };\n",
		cIf, st.Name, iface.Name))
	out.WriteString("}\n\n")
}

// --- 3. MULTI-THREADED WORK-STEALING ACTOR SUPERVISOR WRAPPERS ---

func (g *Generator) emitCloneExpr(t checker.Type, expr string) string {
	if t == nil {
		return expr
	}
	if t.Equals(checker.TypeString) {
		return fmt.Sprintf("vira_str_clone(%s)", expr)
	}
	if _, isTensor := t.(*checker.TensorType); isTensor {
		return fmt.Sprintf("vira_tensor_f32_clone(%s)", expr)
	}
	if sl, isSl := t.(*checker.SliceType); isSl {
		return fmt.Sprintf("%s_clone(&(%s))", g.cSliceName(sl.Elem), expr)
	}
	if st, isSt := t.(*checker.StructType); isSt && !st.IsActor && g.af.StructTypeNeedsFree(st) {
		return fmt.Sprintf("%s_clone(&(%s))", g.cType(st), expr)
	}
	return expr
}

func (g *Generator) emitFreeLValueStmt(out *strings.Builder, indent string, t checker.Type, lval string) {
	if t == nil {
		return
	}
	if t.Equals(checker.TypeString) {
		out.WriteString(fmt.Sprintf("%svira_str_free(&%s);\n", indent, lval))
	} else if _, isTensor := t.(*checker.TensorType); isTensor {
		out.WriteString(fmt.Sprintf("%svira_tensor_f32_free(&%s);\n", indent, lval))
	} else if _, isFut := t.(*checker.FutureType); isFut {
		out.WriteString(fmt.Sprintf("%svira_future_free(&%s);\n", indent, lval))
	} else if sl, isSl := t.(*checker.SliceType); isSl {
		out.WriteString(fmt.Sprintf("%s%s_free(&%s);\n", indent, g.cSliceName(sl.Elem), lval))
	} else if st, isSt := t.(*checker.StructType); isSt && (st.IsActor || g.af.StructTypeNeedsFree(st)) {
		out.WriteString(fmt.Sprintf("%s%s_autofree(&%s);\n", indent, g.cType(st), lval))
	} else if iface, isIf := t.(*checker.InterfaceType); isIf {
		out.WriteString(fmt.Sprintf("%s%s_autofree(&%s);\n", indent, g.cType(iface), lval))
	}
}

func (g *Generator) typeOwnsHeap(t checker.Type) bool {
	if t == nil {
		return false
	}
	if t.Equals(checker.TypeString) {
		return true
	}
	switch v := t.(type) {
	case *checker.TensorType, *checker.FutureType, *checker.SliceType, *checker.InterfaceType:
		return true
	case *checker.StructType:
		return v.IsActor || g.af.StructTypeNeedsFree(v)
	}
	return false
}

func (g *Generator) typeDeferFreeFn(t checker.Type) string {
	if t == nil {
		return ""
	}
	if t.Equals(checker.TypeString) {
		return "(vira_defer_fn)vira_str_free"
	}
	switch v := t.(type) {
	case *checker.TensorType:
		return "(vira_defer_fn)vira_tensor_f32_free"
	case *checker.FutureType:
		return "(vira_defer_fn)vira_future_free"
	case *checker.SliceType:
		return fmt.Sprintf("(vira_defer_fn)%s_free", g.cSliceName(v.Elem))
	case *checker.StructType:
		if v.IsActor || g.af.StructTypeNeedsFree(v) {
			return fmt.Sprintf("(vira_defer_fn)%s_autofree", g.cType(v))
		}
	case *checker.InterfaceType:
		return fmt.Sprintf("(vira_defer_fn)%s_autofree", g.cType(v))
	}
	return ""
}

func (g *Generator) emitActorSupervisorWrapper(out *strings.Builder, actor *checker.StructType, method *checker.FnSig) {
	cActor := g.cStructName(actor.Name)
	innerRet := method.ReturnType
	if res, isRes := innerRet.(*checker.ResultType); isRes {
		innerRet = res.Inner
	}
	cRes := g.cResultName(innerRet)
	envName := fmt.Sprintf("_%s_%s_msg_env", cActor, method.Name)

	// 1. Emit heap-allocated message envelope starting with _FutureHeader_<cRes> _hdr;
	out.WriteString(fmt.Sprintf("typedef struct {\n    _FutureHeader_%s _hdr;\n    %s* self;\n    bool owns_params;\n", cRes, cActor))
	for _, p := range method.Params {
		out.WriteString(fmt.Sprintf("    %s %s;\n", g.cType(p.Type), p.Name))
	}
	out.WriteString(fmt.Sprintf("} %s;\n\n", envName))

	// 1b. Emit drop hook for unconsumed result (used by detached sends and dropped un-awaited Futures)
	out.WriteString(fmt.Sprintf("static void _%s_%s_drop_result(void* _raw_env) {\n", cActor, method.Name))
	out.WriteString(fmt.Sprintf("    %s* env = (%s*)_raw_env;\n", envName, envName))
	out.WriteString("    if (!env) return;\n")
	out.WriteString("    if (env->_hdr.result.is_err) {\n")
	out.WriteString("        vira_str_free(&env->_hdr.result.err);\n")
	if !innerRet.Equals(checker.TypeVoid) && g.typeOwnsHeap(innerRet) {
		out.WriteString("    } else {\n")
		g.emitFreeLValueStmt(out, "        ", innerRet, "env->_hdr.result.val")
	}
	out.WriteString("    }\n")
	out.WriteString("}\n\n")

	// 1c. Emit cloned envelope parameter cleanup (skipping any param aliased directly into result.val)
	out.WriteString(fmt.Sprintf("static void _%s_%s_free_params(%s* env, bool check_ret_alias) {\n", cActor, method.Name, envName))
	out.WriteString("    if (!env || !env->owns_params) return;\n")
	out.WriteString("    (void)check_ret_alias;\n")
	for _, p := range method.Params {
		if !g.typeOwnsHeap(p.Type) {
			continue
		}
		canAliasRet := !innerRet.Equals(checker.TypeVoid) && innerRet.Equals(p.Type)
		if canAliasRet {
			if p.Type.Equals(checker.TypeString) {
				out.WriteString(fmt.Sprintf("    if (!check_ret_alias || (const void*)env->%s.data != (const void*)env->_hdr.result.val.data) {\n", p.Name))
				g.emitFreeLValueStmt(out, "        ", p.Type, "env->"+p.Name)
				out.WriteString("    }\n")
			} else if _, isTensor := p.Type.(*checker.TensorType); isTensor {
				out.WriteString(fmt.Sprintf("    if (!check_ret_alias || (const void*)env->%s.data != (const void*)env->_hdr.result.val.data) {\n", p.Name))
				g.emitFreeLValueStmt(out, "        ", p.Type, "env->"+p.Name)
				out.WriteString("    }\n")
			} else if _, isSl := p.Type.(*checker.SliceType); isSl {
				out.WriteString(fmt.Sprintf("    if (!check_ret_alias || (const void*)env->%s.data != (const void*)env->_hdr.result.val.data) {\n", p.Name))
				g.emitFreeLValueStmt(out, "        ", p.Type, "env->"+p.Name)
				out.WriteString("    }\n")
			} else {
				out.WriteString(fmt.Sprintf("    if (!check_ret_alias || memcmp(&env->%s, &env->_hdr.result.val, sizeof(env->%s)) != 0) {\n", p.Name, p.Name))
				g.emitFreeLValueStmt(out, "        ", p.Type, "env->"+p.Name)
				out.WriteString("    }\n")
			}
		} else {
			g.emitFreeLValueStmt(out, "    ", p.Type, "env->"+p.Name)
		}
	}
	out.WriteString("    env->owns_params = false;\n")
	out.WriteString("}\n\n")

	// 2. Emit worker-thread task callback with per-thread TLS fault boundary (_vira_tls_actor)
	var envArgs []string
	envArgs = append(envArgs, "self")
	for _, p := range method.Params {
		envArgs = append(envArgs, "env->"+p.Name)
	}

	out.WriteString(fmt.Sprintf("static void _%s_%s_worker_task(void* _raw_env) {\n", cActor, method.Name))
	out.WriteString(fmt.Sprintf("    %s* env = (%s*)_raw_env;\n", envName, envName))
	out.WriteString(fmt.Sprintf("    %s* self = env->self;\n", cActor))
	out.WriteString("    bool _is_detached = (__atomic_load_n(&env->_hdr._task.done, __ATOMIC_RELAXED) == -1);\n")
	out.WriteString("    if (self->_ctx.state == VIRA_ACTOR_STOPPED) {\n")
	out.WriteString(fmt.Sprintf("        _%s_%s_free_params(env, false);\n", cActor, method.Name))
	out.WriteString(fmt.Sprintf("        env->_hdr.result = (%s){ .is_err = true, .err = vira_str_lit(\"Actor has stopped due to unhandled faults\", 41) };\n", cRes))
	out.WriteString("        if (_is_detached) {\n")
	out.WriteString(fmt.Sprintf("            _%s_%s_drop_result(env);\n", cActor, method.Name))
	out.WriteString("        }\n")
	out.WriteString("        return;\n")
	out.WriteString("    }\n")
	out.WriteString("    vira_actor_ctx* _prev_tls_actor = _vira_tls_actor;\n")
	out.WriteString("    _vira_tls_actor = &self->_ctx;\n")
	out.WriteString("    self->_ctx.in_actor = true;\n")
	out.WriteString("    self->_ctx.mailbox_lock = 1;\n")
	out.WriteString("    self->_ctx.last_worker_id = _vira_tls_worker_id;\n")
	out.WriteString("    self->_ctx.defer_top = 0;\n")
	out.WriteString("    if (setjmp(self->_ctx.fault_boundary) == 0) {\n")

	callStr := fmt.Sprintf("%s_%s(%s)", cActor, method.Name, strings.Join(envArgs, ", "))
	if _, isRes := method.ReturnType.(*checker.ResultType); isRes {
		out.WriteString(fmt.Sprintf("        env->_hdr.result = %s;\n", callStr))
	} else if innerRet.Equals(checker.TypeVoid) {
		out.WriteString(fmt.Sprintf("        %s;\n", callStr))
		out.WriteString(fmt.Sprintf("        env->_hdr.result = (%s){ .is_err = false };\n", cRes))
	} else {
		out.WriteString(fmt.Sprintf("        %s _val = %s;\n", g.cType(innerRet), callStr))
		out.WriteString(fmt.Sprintf("        env->_hdr.result = (%s){ .is_err = false, .val = _val };\n", cRes))
	}
	out.WriteString("        self->_ctx.defer_top = 0;\n")
	out.WriteString("        vira_arena_reset(&self->_ctx.isolated_heap);\n")
	out.WriteString("        self->_ctx.in_actor = false;\n")
	out.WriteString("        self->_ctx.mailbox_lock = 0;\n")
	out.WriteString("        self->_ctx.restarts = 0;\n")
	out.WriteString("        _vira_tls_actor = _prev_tls_actor;\n")
	out.WriteString("    } else {\n")
	out.WriteString("        // FAULT TRAPPED ON WORKER THREAD! Stack heap locals already unwound; wipe actor's isolated arena slab in O(1)\n")
	out.WriteString("        self->_ctx.defer_top = 0;\n")
	out.WriteString("        vira_arena_reset(&self->_ctx.isolated_heap);\n")
	out.WriteString("        self->_ctx.in_actor = false;\n")
	out.WriteString("        self->_ctx.mailbox_lock = 0;\n")
	out.WriteString("        _vira_tls_actor = _prev_tls_actor;\n")
	out.WriteString("        vira_string _err = self->_ctx.last_error;\n")
	out.WriteString("        self->_ctx.last_error = vira_str_lit(\"\", 0);\n")
	out.WriteString("        if (self->_ctx.restarts < self->_ctx.max_restarts) {\n")
	out.WriteString("            self->_ctx.restarts++;\n")
	out.WriteString("            self->_ctx.state = VIRA_ACTOR_RUNNING;\n")
	out.WriteString(fmt.Sprintf("            %s_supervisor_reset(self);\n", cActor))
	out.WriteString("            printf(\"[vira_supervisor | worker_thread=%d] Actor '%s' (#%d) trapped fault ('%.*s') -> O(1) arena wipe & OneForOne restart [%d/%d]\\n\",\n")
	out.WriteString("                   _vira_tls_worker_id, self->_ctx.name, self->_ctx.id, _err.len, (const char*)_err.data, self->_ctx.restarts, self->_ctx.max_restarts);\n")
	out.WriteString("        } else {\n")
	out.WriteString("            self->_ctx.state = VIRA_ACTOR_STOPPED;\n")
	out.WriteString("        }\n")
	out.WriteString(fmt.Sprintf("        env->_hdr.result = (%s){ .is_err = true, .err = _err };\n", cRes))
	out.WriteString("    }\n")
	out.WriteString(fmt.Sprintf("    _%s_%s_free_params(env, !env->_hdr.result.is_err);\n", cActor, method.Name))
	out.WriteString("    if (_is_detached) {\n")
	out.WriteString(fmt.Sprintf("        _%s_%s_drop_result(env);\n", cActor, method.Name))
	out.WriteString("    }\n")
	out.WriteString("}\n\n")

	// 3. Emit Non-Blocking Future[T] Spawner (_spawn_) — deep-clones heap arguments for concurrent safety
	var paramList []string
	paramList = append(paramList, fmt.Sprintf("%s* self", cActor))
	for _, p := range method.Params {
		paramList = append(paramList, fmt.Sprintf("%s %s", g.cType(p.Type), p.Name))
	}

	out.WriteString(fmt.Sprintf("static inline vira_future %s_spawn_%s(%s) {\n",
		cActor, method.Name, strings.Join(paramList, ", ")))
	out.WriteString(fmt.Sprintf("    %s* env = (%s*)malloc(sizeof(%s));\n", envName, envName, envName))
	out.WriteString("    _vira_record_alloc();\n")
	out.WriteString("    env->self = self;\n")
	out.WriteString("    env->owns_params = true;\n")
	for _, p := range method.Params {
		if p.IsMut {
			out.WriteString(fmt.Sprintf("    env->%s = %s;\n", p.Name, p.Name))
		} else {
			out.WriteString(fmt.Sprintf("    env->%s = %s;\n", p.Name, g.emitCloneExpr(p.Type, p.Name)))
		}
	}
	out.WriteString(fmt.Sprintf("    env->_hdr._task.fn = _%s_%s_worker_task;\n", cActor, method.Name))
	out.WriteString("    env->_hdr._task.env = env;\n")
	out.WriteString("    env->_hdr._task.done = 0;\n")
	out.WriteString("    vira_actor_send(&self->_ctx, &env->_hdr._task);\n")
	out.WriteString(fmt.Sprintf("    return (vira_future){ .task = &env->_hdr._task, .env = env, .drop_fn = _%s_%s_drop_result };\n", cActor, method.Name))
	out.WriteString("}\n\n")

	// 4. Emit Fire-and-Forget Detached Sender (_send_detached_) — deep-clones heap arguments & auto-frees result
	out.WriteString(fmt.Sprintf("static inline void %s_send_detached_%s(%s) {\n",
		cActor, method.Name, strings.Join(paramList, ", ")))
	out.WriteString(fmt.Sprintf("    %s* env = (%s*)malloc(sizeof(%s));\n", envName, envName, envName))
	out.WriteString("    _vira_record_alloc();\n")
	out.WriteString("    env->self = self;\n")
	out.WriteString("    env->owns_params = true;\n")
	for _, p := range method.Params {
		if p.IsMut {
			out.WriteString(fmt.Sprintf("    env->%s = %s;\n", p.Name, p.Name))
		} else {
			out.WriteString(fmt.Sprintf("    env->%s = %s;\n", p.Name, g.emitCloneExpr(p.Type, p.Name)))
		}
	}
	out.WriteString(fmt.Sprintf("    env->_hdr._task.fn = _%s_%s_worker_task;\n", cActor, method.Name))
	out.WriteString("    env->_hdr._task.env = env;\n")
	out.WriteString("    env->_hdr._task.next_actor_msg = NULL;\n")
	out.WriteString("    env->_hdr._task.done = -1;\n")
	out.WriteString("    vira_actor_send(&self->_ctx, &env->_hdr._task);\n")
	out.WriteString("}\n\n")

	// 5. Emit Zero-Alloc Synchronous Shorthand (_supervise_ = stack-allocated env)
	out.WriteString(fmt.Sprintf("static inline %s %s_supervise_%s(%s) {\n",
		cRes, cActor, method.Name, strings.Join(paramList, ", ")))
	out.WriteString(fmt.Sprintf("    %s env;\n", envName))
	out.WriteString("    env.self = self;\n")
	out.WriteString("    env.owns_params = false;\n")
	for _, p := range method.Params {
		out.WriteString(fmt.Sprintf("    env.%s = %s;\n", p.Name, p.Name))
	}
	out.WriteString(fmt.Sprintf("    env._hdr._task.fn = _%s_%s_worker_task;\n", cActor, method.Name))
	out.WriteString("    env._hdr._task.env = &env;\n")
	out.WriteString("    env._hdr._task.next_actor_msg = NULL;\n")
	out.WriteString("    env._hdr._task.done = 0;\n")
	out.WriteString("    vira_actor_send(&self->_ctx, &env._hdr._task);\n")
	out.WriteString("    vira_scheduler_await(&env._hdr._task);\n")
	out.WriteString("    return env._hdr.result;\n")
	out.WriteString("}\n\n")
}

